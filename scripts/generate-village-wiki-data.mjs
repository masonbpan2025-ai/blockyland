// node scripts/generate-village-wiki-data.mjs
//
// Reads the saved wiki pages (docs/structure-audit/wiki/Village/wiki.txt and Village_Structure/wiki.txt; refresh them
// with `node scripts/fetch-wiki-structure.mjs Village` and the Village/Structure fetch) and writes
// src/villageWikiData.js: per village type, the infobox block list, the abandoned-only and normal-only blocks, and
// every template name with its one-line description. tests/villageWiki.test.js checks the file is up to date.
import { readFileSync, writeFileSync } from 'node:fs';

export function parseVillageWiki(villageText, structureText) {
  // Infobox: "Plains Village:" headings, each followed by {{BlockLink|...}} lines.
  const a = villageText.indexOf('| blocks =');
  const b = villageText.indexOf('\n|', a + 10);
  const infobox = {};
  let current = null;
  for (const line of villageText.slice(a, b).split('\n')) {
    const heading = line.match(/^(\w+) Village:/);
    if (heading) { current = heading[1].toLowerCase(); infobox[current] = { blocks: [], abandonedOnly: [], normalOnly: [], bedrockOnly: [] }; continue; }
    const m = line.match(/\{\{BlockLink\|(?:id=([^|}]+)\|)?([^|}]+)/);
    if (!m || !current) continue;
    const name = wikiBlockId(m[1] || m[2]);
    const entry = infobox[current];
    if (/only\|(?:BE|bedrock)/i.test(line)) { entry.bedrockOnly.push(name); continue; }
    entry.blocks.push(name);
    if (/abandoned villages only/.test(line)) entry.abandonedOnly.push(name);
    if (/normal villages only/.test(line)) entry.normalOnly.push(name);
  }
  // Templates: rows of the "All structures" table, grouped by their biome section.
  const lines = structureText.split('\n');
  const templates = {};
  let section = null;
  let folder = null;
  for (let i = lines.indexOf('=== All structures ==='); i >= 0 && i < lines.length; i++) {
    const line = lines[i];
    const heading = line.match(/^==== (\w+) biome structure variants ====/);
    if (heading) { section = heading[1].toLowerCase(); templates[section] = []; continue; }
    if (/^==== Structures common/.test(line)) { section = null; continue; }
    const codes = [...line.matchAll(/\{\{code\|([^}]+)\}\}/g)].map((x) => x[1]);
    if (line.startsWith('!') && codes.length) { folder = codes[0]; continue; }
    if (!section || !line.startsWith('|') || line.startsWith('|-') || codes.length !== 1) continue;
    const description = (lines[i + 1] || '').replace(/^\|\s*/, '')
      .replace(/<ref[^>]*>.*?<\/ref>|<ref[^/]*\/>/g, '').replace(/\{\{only\|[^}]*\}\}/g, '')
      .replace(/\[\[(?:[^|\]]*\|)?([^\]]*)\]\]/g, '$1').replace(/\{\{[^}]*\}\}/g, '').trim();
    templates[section].push({ name: codes[0].replace(/^\//, ''), folder, description });
  }
  // The abandoned ("zombie") variant's own house pools, from the file tree: village/<type>/zombie/houses/*.
  const zombieHouses = {};
  const path = [];
  for (const line of structureText.split('\n')) {
    if (line.startsWith('=== All structures')) break;
    const m = line.match(/^(\*+)\s*(?:\{\{nbt\|compound\}\}\s*)?([^:]+?)(?::.*)?$/);
    if (!m) continue;
    path.length = m[1].length - 1;
    path[m[1].length - 1] = m[2].trim();
    if (path.length === 5 && path[2] === 'zombie' && path[3] === 'houses' && path[4].startsWith(path[1] + '_')) {
      (zombieHouses[path[1]] ??= []).push(path[4]);
    }
  }
  return { infobox, templates, zombieHouses };
}

/** "Hay Bale" -> hay_block, "Jack o'Lantern" -> jack_o_lantern: the wiki's names to this game's block ids. */
export function wikiBlockId(name) {
  const id = name.trim().toLowerCase().replace(/'/g, '').replace(/\s+/g, '_');
  return { hay_bale: 'hay_block', jack_olantern: 'jack_o_lantern' }[id] ?? id;
}

export function render(data) {
  return `// GENERATED by scripts/generate-village-wiki-data.mjs from the saved wiki pages -- do not edit by hand.
// Source: https://minecraft.wiki/w/Village (infobox) and https://minecraft.wiki/w/Village/Structure (All structures).
export const VILLAGE_WIKI = ${JSON.stringify(data, null, 2)};
`;
}

if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, '/').replace(/^\//, '')}` || process.argv[1]?.endsWith('generate-village-wiki-data.mjs')) {
  const data = parseVillageWiki(
    readFileSync('docs/structure-audit/wiki/Village/wiki.txt', 'utf8'),
    readFileSync('docs/structure-audit/wiki/Village_Structure/wiki.txt', 'utf8')
  );
  writeFileSync('src/villageWikiData.js', render(data));
  for (const [type, entry] of Object.entries(data.infobox)) console.log(type, entry.blocks.length, 'blocks;', (data.templates[type] ?? []).length, 'templates');
}
