// Lay out Three Islands, Three Weddings from the measured voice clips: every line starts after the
// previous one ends plus its `gap`, every scene holds at least its minimum length, and nothing is ever sped up.
// Writes src/cinema/wedTimeline.js (line starts, scene spans, total duration).
//   node scripts/narrate-claude.mjs civ-weddings && node scripts/layout-wed.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { LINES, SCENES } from '../src/cinema/wedLines.js';

const manifest = JSON.parse(readFileSync('public/cinema-weddings/audio/manifest.json', 'utf8'));
const round = t => Math.round(t * 20) / 20;
const START = {}, SCENE = {};
let t = 0;
for (const [name, min] of SCENES) {
  const from = t;
  for (const line of LINES.filter(l => l.scene === name)) {
    const clip = manifest[line.id]; if (!clip) throw new Error(`No clip for ${line.id}; run narrate-claude.mjs civ-weddings`);
    t = round(t + (line.gap ?? .5)); START[line.id] = t; t += clip.duration + (line.wait ?? 0);
  }
  t = round(Math.max(from + min, t + .8)); SCENE[name] = [from, t];
}
const unknown = LINES.filter(l => !SCENE[l.scene]); if (unknown.length) throw new Error(`Lines in unknown scenes: ${unknown.map(l => l.id)}`);
const body = `// Generated by scripts/layout-wed.mjs from the measured voice clips. Do not edit by hand.
export const START = ${JSON.stringify(START)};
export const SCENE = ${JSON.stringify(SCENE)};
export const DURATION = ${t};
`;
writeFileSync('src/cinema/wedTimeline.js', body);
console.log(`Laid out ${LINES.length} lines in ${SCENES.length} scenes: ${Math.floor(t / 60)}:${String(Math.round(t % 60)).padStart(2, '0')} (${t} s).`);
for (const [k, [a, b]] of Object.entries(SCENE)) console.log(k.padEnd(10), a.toFixed(1).padStart(6), b.toFixed(1).padStart(6), (b - a).toFixed(1).padStart(5));
