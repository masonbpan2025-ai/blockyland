import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {gunzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';

// Offline, reproducible import of the published gd.py 0.11.0 source dataset.
// Usage: node scripts/import-geometry-dash-levels.mjs path/to/official_levels.json
const input=process.argv[2];if(!input)throw new Error('Pass the original official_levels.json dataset');
const bytes=await readFile(input),source=JSON.parse(bytes);
const names=['Back On Track','Polargeist','Dry Out','Base After Base','Cant Let Go'];
const levels=names.map(name=>{
  const text=gunzipSync(Buffer.from(source[name],'base64url')).toString();
  const parts=text.split(';'),header=parts.shift();
  const objects=parts.filter(Boolean).map(part=>{
    const tokens=part.split(','),p={};for(let i=0;i<tokens.length;i+=2)p[tokens[i]]=tokens[i+1];
    return [+p[1],+p[2],+p[3],+(p[4]??0),+(p[5]??0),+(p[6]??0),+(p[32]??1),+(p[12]??0)];
  });
  return {name,header,sha256:createHash('sha256').update(text).digest('hex'),objects};
});
const directory=new URL('../src/mods/voxel-dash/data/',import.meta.url);await mkdir(directory,{recursive:true});
await writeFile(new URL('original-levels.js',directory),'// Generated by scripts/import-geometry-dash-levels.mjs; never hand-edit coordinates.\nexport default '+JSON.stringify({source:'gd.py 0.11.0 / gd/official_levels.json',sourceSha256:createHash('sha256').update(bytes).digest('hex'),levels})+';\n');
console.log(levels.map(l=>`${l.name}: ${l.objects.length} original objects`).join('\n'));
