import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({headless:true, channel: process.env.MOD_BROWSER_CHANNEL ?? 'msedge'});
const page = await browser.newPage();
page.setDefaultNavigationTimeout(60000);
const base = process.env.MOD_INSPECTOR_URL ?? 'http://127.0.0.1:3100';
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(`${base}/mob-debug.html?mob=tournament_host`, {waitUntil:'domcontentloaded'});
  await page.waitForFunction(() => window.__debugSession?.mob);
  const options = () => page.locator('#mob option').evaluateAll(nodes=>nodes.map(node=>node.value));
  assert.ok(!(await options()).includes('tournament_host'));
  assert.equal(await page.locator('#content-source').inputValue(), '');
  console.log('Mob Inspector base scope ready.');
  for(let cycle=0;cycle<2;cycle++) {
    await page.locator('#content-source').selectOption('dragonball_tournament');
    await page.waitForFunction(() => window.__debugSession?.mob?.modId === 'dragonball_tournament');
    assert.deepEqual((await options()).sort(), ['dragonball_tournament:jackie_chun','dragonball_tournament:site_manager','dragonball_tournament:tournament_host']);
    await page.locator('#mob').selectOption('dragonball_tournament:jackie_chun');
    await page.locator('#step').click();
    assert.equal(await page.locator('#error').textContent(), '');
    await page.locator('#content-source').selectOption('');
    await page.waitForFunction(()=>window.__debugSession?.mob?.type==='blaze');
    assert.equal(await page.evaluate(()=>window.__debugSession.manager.mobProviders.size),0);
    assert.ok((await options()).includes('zombie'));
  }
  await page.locator('#content-source').selectOption('rescue_adventure');
  await page.waitForFunction(()=>window.__debugSession?.mob?.modId==='rescue_adventure');
  assert.equal((await options()).length,16);
  assert.ok((await options()).every(id=>id.startsWith('rescue_adventure:')));
  await page.locator('#mob').selectOption('rescue_adventure:royal_guard');
  await page.locator('#step').click();
  assert.equal(await page.locator('#error').textContent(),'');
  await page.locator('#content-source').selectOption('');
  await page.waitForFunction(()=>window.__debugSession?.mob?.type==='blaze');
  assert.equal(await page.evaluate(()=>window.__debugSession.manager.mobProviders.size),0);
  await page.goto(`${base}/item-debug.html`, {waitUntil:'domcontentloaded'});
  console.log('Mob Inspector switch/unload cycles passed.');
  await page.waitForFunction(()=>document.querySelector('#resource').options.length>0);
  await page.locator('#content-source').selectOption('dragonball_tournament');
  assert.equal(await page.locator('#resource option').count(),0);
  assert.match(await page.locator('#badge').textContent(),/No resources/);
  assert.equal(await page.locator('#facts').textContent(),'');
  await page.locator('#content-source').selectOption('');
  assert.ok(await page.locator('#resource option').count()>0);
  assert.equal(await page.locator('#error').textContent(),'');
  await page.locator('#content-source').selectOption('rescue_adventure');
  assert.equal(await page.locator('#resource option').count(),8);
  assert.equal(await page.locator('#error').textContent(),'');
  await page.locator('#content-source').selectOption('');
  await page.goto(`${base}/structure-inspector.html`, {waitUntil:'domcontentloaded'});
  console.log('Resource Inspector scope switching passed.');
  await page.waitForFunction(()=>document.querySelector('#structure').options.length>0);
  await page.locator('#content-source').selectOption('dragonball_tournament');
  assert.equal(await page.locator('#structure option').count(),0);
  assert.match(await page.locator('#plan-info').textContent(),/does not register/);
  assert.equal(await page.locator('#plan-summary').textContent(),'');
  assert.equal(await page.locator('#piece-graph').textContent(),'');
  await page.locator('#content-source').selectOption('');
  assert.ok(await page.locator('#structure option').count()>0);
  assert.equal(errors.length,0,errors.join('\n'));
  const response = await page.request.get(`${base}/api/designed-worlds/World_Martial_Arts_Tournament.json`);
  assert.equal(response.status(),200);
  assert.equal((await response.json()).mechanism,'dragonball_tournament');
  await page.goto(`${base}/`, {waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>window.game?.modLoader && window.game?.mobs);
  assert.equal(await page.locator('#tournament-setup-modal').count(),0);
  const result = await page.evaluate(()=>window.game.openDesignedWorld({filename:'World_Martial_Arts_Tournament.json'}));
  assert.equal(result.modId,'dragonball_tournament');
  assert.equal(await page.locator('#tournament-setup-modal').count(),1);
  await page.evaluate(()=>window.game.modLoader.closeWorld());
  assert.equal(await page.locator('#tournament-setup-modal').count(),0);
  assert.equal(await page.evaluate(()=>window.game.mobs.mobProviders.size),0);
  assert.equal(errors.length,0,errors.join('\n'));
  console.log('PASS: all three Inspector scopes, repeated mod unload/reload, and mod map API.');
} catch (error) {
  console.error('Browser state:', await page.locator('body').innerText(), errors);
  throw error;
} finally { await browser.close(); }
