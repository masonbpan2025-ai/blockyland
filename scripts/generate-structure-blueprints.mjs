// node scripts/generate-structure-blueprints.mjs
//
// Turns the {{layered blueprint}} drawings on the wiki's "<Structure>/Structure" pages (saved under
// docs/structure-audit/wiki/) into src/worldgen/generators/structureBlueprintData.js: one block list per drawing, in
// the drawing's own frame (x = column, z = row, y = layer - lowest layer), with facings from the shared rules
// (scripts/blueprintStates.mjs). Structure generators place, rotate and vary these.
import { readFileSync, writeFileSync } from 'node:fs';
import { parseBlueprints } from './villageBlueprintParse.mjs';
import { resolveCells } from './blueprintStates.mjs';

/** Which drawings to convert. `page` is the saved Structure page, `name` the blueprint's name on it. */
export const TARGETS = [
  { key: 'desert_pyramid', page: 'Desert_Pyramid_Structure', name: 'Desert Pyramid', stairsFromNeighbours: true },
  { key: 'igloo', page: 'Igloo_Structure', name: 'Igloo' },
  { key: 'pillager_outpost/watchtower', page: 'Pillager_Outpost_Structure', name: 'Pillager Outpost', stairsFromNeighbours: true },
  { key: 'pillager_outpost/feature_cage', page: 'Pillager_Outpost_Structure', name: 'Cage', variant: 'a' },
  { key: 'pillager_outpost/feature_cage_allay', page: 'Pillager_Outpost_Structure', name: 'Cage', variant: 'b' },
  { key: 'pillager_outpost/feature_logs', page: 'Pillager_Outpost_Structure', name: 'Logs' },
  { key: 'pillager_outpost/feature_targets', page: 'Pillager_Outpost_Structure', name: 'Target' },
  { key: 'pillager_outpost/feature_tent1', page: 'Pillager_Outpost_Structure', name: 'Tent 1' },
  { key: 'pillager_outpost/feature_tent2', page: 'Pillager_Outpost_Structure', name: 'Tent 2' }
];

export function convertStructureBlueprint(bp, options = {}) {
  const { cells, unknown } = resolveCells(bp, options);
  const layers = cells.map((c) => c.layer);
  const minLayer = Math.min(...layers);
  const maxLayer = Math.max(...layers);
  // The size is the occupied cells' extent (some drawings carry trailing spaces on a row).
  const width = Math.max(...cells.map((c) => c.x)) + 1;
  const depth = Math.max(...cells.map((c) => c.z)) + 1;
  const palette = [];
  const index = new Map();
  const id = (name, props) => {
    const key = name + JSON.stringify(props ?? {});
    if (!index.has(key)) { index.set(key, palette.length); palette.push(props ? { Name: 'minecraft:' + name, Properties: props } : { Name: 'minecraft:' + name }); }
    return index.get(key);
  };
  const blocks = [];
  const entities = [];
  for (const c of cells) {
    const y = c.layer - minLayer;
    if (c.state.entity) { entities.push({ type: c.state.entity.replace(/\s+/g, '_'), tags: c.entry.mods, pos: [c.x, y, c.z] }); continue; }
    blocks.push([c.x, y, c.z, id(c.state.name, c.state.props)]);
  }
  return { size: [width, maxLayer - minLayer + 1, depth], minLayer, palette, blocks: blocks.map((b) => b.join(',')).join(';'), entities, unknown };
}

const isMain = process.argv[1]?.endsWith('generate-structure-blueprints.mjs');
if (isMain) {
  const out = {};
  for (const target of TARGETS) {
    const text = readFileSync(`docs/structure-audit/wiki/${target.page}/wiki.txt`, 'utf8');
    const bp = parseBlueprints(text, target.page).find((b) => b.name === target.name);
    if (!bp) throw new Error(`no blueprint "${target.name}" on ${target.page}`);
    const converted = convertStructureBlueprint(bp, { stairsFromNeighbours: target.stairsFromNeighbours, variant: target.variant ?? null });
    if (converted.unknown.length) console.log(target.key, 'unknown blocks:', converted.unknown.join(', '));
    delete converted.unknown;
    out[target.key] = converted;
    console.log(target.key, converted.size.join('x'), 'from layer', converted.minLayer, `${converted.blocks.split(';').length} blocks`, `${converted.entities.length} entities`);
  }
  writeFileSync('src/worldgen/generators/structureBlueprintData.js', `// GENERATED by scripts/generate-structure-blueprints.mjs from the Minecraft Wiki's structure blueprints
// (the "<Structure>/Structure" pages, CC BY-NC-SA 3.0) -- do not edit by hand.
export const STRUCTURE_BLUEPRINTS = ${JSON.stringify(out)};
`);
}
