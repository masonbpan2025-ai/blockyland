// node scripts/generate-all-structure-blueprints.mjs
//
// Converts EVERY {{layered blueprint}} saved under docs/structure-audit/wiki/<Structure>_Structure/ (the page and its
// LoadPage subpages in sub/) into src/worldgen/generators/blueprints/<structure>.js, keyed by blueprint name. Village
// blueprints have their own generator (generate-village-blueprints.mjs) and are skipped.
//
// Stairs: drawings that rotate their stairs follow the tested sprite rule (base north, clockwise); drawings that draw
// every stair unrotated get their facing from neighbours (as the desert pyramid's page instructs).
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { parseBlueprints } from './villageBlueprintParse.mjs';
import { convertStructureBlueprint } from './generate-structure-blueprints.mjs';

const WIKI = 'docs/structure-audit/wiki';
const OUT = 'src/worldgen/generators/blueprints';

export function slug(text) {
  return String(text).toLowerCase().replace(/'/g, '').replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
}

export function collectBlueprints() {
  const out = {};
  for (const dir of readdirSync(WIKI)) {
    if (!dir.endsWith('_Structure') || dir.startsWith('Village')) continue;
    const structure = slug(dir.replace(/_Structure$/, ''));
    const files = [[join(WIKI, dir, 'wiki.txt'), null]];
    if (existsSync(join(WIKI, dir, 'sub'))) for (const f of readdirSync(join(WIKI, dir, 'sub'))) files.push([join(WIKI, dir, 'sub', f), f.replace(/\.txt$/, '')]);
    for (const [file, subName] of files) {
      const text = readFileSync(file, 'utf8');
      const blueprints = parseBlueprints(text, file);
      blueprints.forEach((bp, i) => {
        const base = slug(bp.name || subName || 'blueprint') || 'blueprint';
        let key = base;
        let n = 2;
        while (out[structure]?.[key]) key = `${base}_${n++}`;
        (out[structure] ??= {})[key] = { bp, source: file.replace(/\\/g, '/'), subName, index: i };
      });
    }
  }
  return out;
}

const isMain = process.argv[1]?.endsWith('generate-all-structure-blueprints.mjs');
if (isMain) {
  const { createBlockIdResolver } = await import('../src/worldgen/blockIds.js');
  const { BLOCKS } = await import('../src/blocks.js');
  const resolver = createBlockIdResolver(BLOCKS);
  mkdirSync(OUT, { recursive: true });
  const all = collectBlueprints();
  for (const [structure, entries] of Object.entries(all)) {
    const data = {};
    const unresolved = new Set();
    for (const [key, { bp, source }] of Object.entries(entries)) {
      const rotatedStairs = Object.values(bp.legend).some((e) => / stairs$/.test(e.name) && e.rot !== 0);
      let converted;
      try { converted = convertStructureBlueprint(bp, { stairsFromNeighbours: !rotatedStairs }); } catch (error) { console.log(`  ${structure}/${key}: ${error.message}`); continue; }
      for (const u of converted.unknown) unresolved.add(`${u} (unknown)`);
      for (const p of converted.palette) if (resolver.resolveState({ name: p.Name, properties: {} }) === null) unresolved.add(p.Name.replace('minecraft:', ''));
      delete converted.unknown;
      data[key] = { ...converted, source };
    }
    const file = `${OUT}/${structure}.js`;
    writeFileSync(file, `// GENERATED by scripts/generate-all-structure-blueprints.mjs from the Minecraft Wiki (CC BY-NC-SA 3.0) -- do not edit.
export const BLUEPRINTS = ${JSON.stringify(data)};
`);
    console.log(structure.padEnd(22), Object.keys(data).length, 'blueprints', unresolved.size ? `UNRESOLVED: ${[...unresolved].join(', ')}` : '');
  }
}
