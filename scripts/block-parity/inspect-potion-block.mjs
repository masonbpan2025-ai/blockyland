// The sapling-batch merge resurrected a block of hand-written potion items in src/blocks.js that the
// item-parity work had already moved to the generated src/extraPotions.js. Keeping both trips the
// collision guard at the bottom of blocks.js ("extraPotions collision: 'awkward_potion' is already a
// hand-written item"), which is exactly what that guard exists to catch.
//
// This reports the extent of the resurrected block and whether every name in it is also in
// extraPotions.js, so the removal is proven redundant rather than assumed.
import { readFileSync } from 'node:fs';

// Run against a merge worktree: node scripts/block-parity/inspect-potion-block.mjs <worktree-root>
const ROOT = (process.argv[2] ?? '.').replace(/\\/g, '/').replace(/\/$/, '');
const W = `${ROOT}/src/blocks.js`;
const { POTION_ITEMS } = await import(`file:///${ROOT}/src/extraPotions.js`);
const lines = readFileSync(W, 'utf8').split(/\r?\n/);

const start = lines.findIndex((l) => /^\s+awkward_potion:/.test(l));
if (start < 0) { console.log('no hand-written awkward_potion found; nothing to remove'); process.exit(0); }

// The block runs while lines still look like generated potion entries.
const isPotionEntry = (l) => /^\s+[a-z0-9_]*(potion|bottle)[a-z0-9_]*:\s*\{/.test(l);
let end = start;
while (end < lines.length && (isPotionEntry(lines[end]) || lines[end].trim() === '')) end++;

const block = lines.slice(start, end).filter((l) => l.trim());
console.log(`block spans lines ${start + 1}..${end} (${block.length} entries)`);

const names = block.map((l) => l.trim().match(/^([a-z0-9_]+):/)?.[1]).filter(Boolean);
const inExtra = names.filter((n) => n in POTION_ITEMS);
const notInExtra = names.filter((n) => !(n in POTION_ITEMS));
console.log(`  names: ${names.length}`);
console.log(`  also generated by extraPotions.js: ${inExtra.length}`);
console.log(`  NOT in extraPotions.js: ${notInExtra.length}${notInExtra.length ? ' -> ' + notInExtra.join(', ') : ''}`);

// Any line that is not a potion entry inside the span, or a blank, would be a sign the heuristic ran
// past the block.
const unexpected = lines.slice(start, end).filter((l) => l.trim() && !isPotionEntry(l));
if (unexpected.length) {
  console.log('UNEXPECTED lines inside the span, refusing to remove:');
  for (const l of unexpected) console.log('   ' + l.trim().slice(0, 110));
  process.exit(1);
}

if (notInExtra.length) {
  console.log('refusing: some entries are not generated, so removing them would lose items');
  process.exit(1);
}

console.log('\nSafe to remove: every entry is also generated by extraPotions.js.');
