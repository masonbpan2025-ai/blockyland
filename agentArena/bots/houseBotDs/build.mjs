#!/usr/bin/env node
// Build the house bots: each strategy the arena runs must be one self-contained file (no imports in the sandbox), so
// bots/<game>.js is bots/core.js followed by bots/<game>.game.js. Edit those two, then:
//   node agentArena/bots/build.mjs            (writes bots/skywars.js and bots/bedwars.js)
//   node agentArena/bots/build.mjs --check    (fails if a built file is out of date)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';

const here = import.meta.dirname;
const GAMES = ['skywars', 'bedwars'];

/** The built strategy for a game, from its sources. */
export function buildBot(game) {
  const core = readFileSync(path.join(here, 'core.js'), 'utf8');
  const rules = readFileSync(path.join(here, `${game}.game.js`), 'utf8');
  return `// GENERATED by agentArena/bots/build.mjs from bots/core.js and bots/${game}.game.js: edit those, then build.\n\n${core.trim()}\n\n${rules.trim()}\n`;
}

const check = process.argv.includes('--check');
let stale = 0;
for (const game of GAMES) {
  if (!existsSync(path.join(here, `${game}.game.js`))) continue;
  const out = path.join(here, `${game}.js`), text = buildBot(game);
  if (check) { if (!existsSync(out) || readFileSync(out, 'utf8') !== text) { console.log(`${game}.js is out of date: node agentArena/bots/build.mjs`); stale++; } }
  else { writeFileSync(out, text); console.log(`built ${path.relative(process.cwd(), out)}`); }
}
process.exitCode = stale ? 1 : 0;
