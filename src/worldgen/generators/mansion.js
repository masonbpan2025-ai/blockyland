// Woodland mansion: a procedural floor plan of rooms over three floors.
//
// REWRITE NOTES, from deviation 0f, which records why the first attempt was reverted rather than committed:
//   1. 'secret' is EXCLUDED from the room-type draw and appended exactly once at the END of the list. Drawing
//      it and then overwriting the last entry could leave TWO secret rooms, because the entry it overwrote may
//      not have been the only one drawn. The secret room is built by construction, not by correction.
//   2. Room cells are counted in PIECE-LOCAL coordinates. The first attempt divided ABSOLUTE block coordinates
//      by the room size, so the chunk offset inflated the count beyond one floor's grid.
//   3. The grid is 2x2 rooms per floor rather than 3x3, which keeps the plan reviewable while leaving every
//      structural property -- three floors, doorways between neighbours, one secret room on top -- intact.
//
// From the wiki (`Woodland Mansion`, 1.21.4 revision) and this repository's registry entry: dark forest only;
// rooms over THREE floors; named rooms including a prison, a dining room, a library and storage; a secret room
// on the top floor holding a diamond block; vindicators and evokers inside; mansion loot in the chests. The
// registry also records that the Pale Garden variant is post-1.21.4 and deliberately excluded.
//
// PROVENANCE: no Minecraft assets. The plan is generated by code from the described rooms and materials, so the
// LAYOUT is a clean-room approximation while the three-floor composition, the connectivity, chunk-safe
// realization and the loot are the engine's real behaviour.

import { StructurePiece, StructureStart } from '../start.js';
import { LegacyRandom, legacyFromLargeFeatureSeed } from '../random.js';
import { placeTemplate } from '../templatePlacement.js';
import { StructureTemplate } from '../template.js';
import { createBlockIdResolver } from '../blockIds.js';

export const MANSION_MATERIALS = {
  plank: 'minecraft:dark_oak_planks',
  log: 'minecraft:dark_oak_log',
  stair: 'minecraft:dark_oak_stairs',
  fence: 'minecraft:dark_oak_fence',
  pane: 'minecraft:glass_pane',
  wool: 'minecraft:white_wool',
  carpet: 'minecraft:red_carpet',
  shelf: 'minecraft:bookshelf',
  web: 'minecraft:cobweb',
  torch: 'minecraft:torch',
  diamond: 'minecraft:diamond_block',
  obsidian: 'minecraft:obsidian',
  chest: 'minecraft:chest',
  loot: 'minecraft:chests/woodland_mansion'
};

export const MANSION_FLOORS = 3;
export const MANSION_ROOMS_PER_SIDE = 2;
export const MANSION_ROOM_SIZE = 11;
export const MANSION_ROOM_HEIGHT = 6;
export const MANSION_GRID_CELLS = MANSION_ROOMS_PER_SIDE * MANSION_ROOMS_PER_SIDE;

/** Named rooms. `secret` is deliberately absent: it is appended once, by construction. */
export const MANSION_ROOM_TYPES = ['dining', 'library', 'bedroom', 'storage', 'prison', 'map_room', 'empty'];

/** The room types in grid order, with exactly one secret room at the very end (the top floor). */
export function planRooms(seed) {
  const random = new LegacyRandom(BigInt(seed) * 6364136223846793005n + 1442695040888963407n);
  const total = MANSION_GRID_CELLS * MANSION_FLOORS;
  const list = [];
  for (let i = 0; i < total - 1; i++) list.push(MANSION_ROOM_TYPES[random.nextIntBound(MANSION_ROOM_TYPES.length)]);
  list.push('secret');
  return list;
}

/** The floor a room-type index belongs to, DERIVED rather than assumed. */
export function floorOfRoom(index) {
  return Math.floor(index / MANSION_GRID_CELLS);
}

export function buildMansion({ seed = 0, roomTypes = null } = {}) {
  const side = MANSION_ROOMS_PER_SIDE;
  const room = MANSION_ROOM_SIZE;
  const floorHeight = MANSION_ROOM_HEIGHT;
  const width = side * room;
  const height = MANSION_FLOORS * floorHeight + 1;
  const size = [width, height, width];
  const palette = [{ Name: 'minecraft:air' }];
  const index = new Map();
  const material = (name) => {
    if (!index.has(name)) { index.set(name, palette.length); palette.push({ Name: name }); }
    return index.get(name);
  };
  const blocks = [];
  // A block outside the declared size would be written outside the piece box: a plan whose advertised box is a
  // lie, and a chunk-clipping hazard. It is an error, not a silent extra block.
  const push = (x, y, z, state, nbt = null) => {
    if (x < 0 || y < 0 || z < 0 || x >= width || y >= height || z >= width) {
      throw new Error('mansion: block ' + x + ',' + y + ',' + z + ' is outside ' + size.join('x'));
    }
    blocks.push(nbt ? { pos: [x, y, z], state, nbt } : { pos: [x, y, z], state });
  };
  const m = (key) => material(MANSION_MATERIALS[key]);
  const types = roomTypes ?? planRooms(seed);
  const mid = Math.floor(room / 2);

  for (let floor = 0; floor < MANSION_FLOORS; floor++) {
    const base = floor * floorHeight;
    for (let rx = 0; rx < side; rx++) {
      for (let rz = 0; rz < side; rz++) {
        const cell = floor * MANSION_GRID_CELLS + rz * side + rx;
        const type = types[cell];
        const x0 = rx * room;
        const z0 = rz * room;
        for (let x = 0; x < room; x++) {
          for (let z = 0; z < room; z++) {
            push(x0 + x, base, z0 + z, m('plank'));
            push(x0 + x, base + floorHeight, z0 + z, m('plank'));
          }
        }
        for (let y = 1; y < floorHeight; y++) {
          for (let x = 0; x < room; x++) {
            for (let z = 0; z < room; z++) {
              const edge = x === 0 || x === room - 1 || z === 0 || z === room - 1;
              if (!edge) continue;
              // DOORWAYS in the middle of every side at walking height: this is what makes the grid a mansion
              // rather than a set of sealed cells, and the tests assert it.
              const doorway = (x === mid || x === mid + 1 || z === mid || z === mid + 1)
                && ((x === mid && (z === 0 || z === room - 1)) || (z === mid && (x === 0 || x === room - 1)));
              if (doorway && y <= 2) continue;
              const corner = (x === 0 || x === room - 1) && (z === 0 || z === room - 1);
              const outer = rx === 0 || rz === 0 || rx === side - 1 || rz === side - 1;
              const window = outer && y === Math.floor(floorHeight / 2) && (x + z) % 4 === 0;
              push(x0 + x, base + y, z0 + z, corner ? m('log') : window ? m('pane') : m('plank'));
            }
          }
        }
        const cx = x0 + mid;
        const cz = z0 + mid;
        if (type === 'dining') {
          for (let x = 3; x < room - 3; x++) push(x0 + x, 1, cz, m('stair'));
          push(cx, 2, cz, m('torch'));
        } else if (type === 'library') {
          for (let z = 2; z < room - 2; z++) {
            push(x0 + 1, 1, z0 + z, m('shelf'));
            push(x0 + 1, 2, z0 + z, m('shelf'));
            push(x0 + room - 2, 1, z0 + z, m('shelf'));
          }
        } else if (type === 'bedroom') {
          push(cx, 1, cz, m('wool'));
          push(cx, 1, cz + 1, m('carpet'));
        } else if (type === 'storage') {
          for (const [dx, dz] of [[2, 2], [room - 3, 2], [2, room - 3]]) {
            push(x0 + dx, 1, z0 + dz, m('chest'), { id: 'minecraft:chest', LootTable: MANSION_MATERIALS.loot });
          }
        } else if (type === 'prison') {
          for (let x = 3; x < room - 3; x++) { push(x0 + x, 1, z0 + 3, m('fence')); push(x0 + x, 2, z0 + 3, m('fence')); }
          push(x0 + 2, 1, z0 + 2, m('web'));
        } else if (type === 'map_room') {
          push(cx, 1, cz, m('carpet'));
          push(cx, 2, cz, m('torch'));
        } else if (type === 'secret') {
          // Built by construction, so it exists exactly once and on the top floor.
          for (let y = 1; y < floorHeight; y++) {
            for (let x = 1; x < room - 1; x++) {
              push(x0 + x, base + y, z0 + 1, m('obsidian'));
              push(x0 + x, base + y, z0 + room - 2, m('obsidian'));
            }
          }
          push(cx, base + 1, cz, m('diamond'));
          push(cx, base + 2, cz, m('chest'), { id: 'minecraft:chest', LootTable: MANSION_MATERIALS.loot });
        }
      }
    }
  }
  for (let x = 0; x < width; x++) for (let z = 0; z < width; z++) push(x, height - 1, z, m('stair'));

  return {
    size,
    palette,
    blocks,
    entities: [],
    meta: { roomTypes: types, floors: MANSION_FLOORS, roomsPerSide: side, roomSize: room, roomHeight: floorHeight }
  };
}

/** The inhabitants, placed as markers: vanilla populates a mansion through spawn overrides and groups. */
export const MANSION_INHABITANTS = ['vindicator', 'evoker'];

export function generateMansion({ seed, chunkX, chunkZ, context }) {
  const originX = chunkX * 16 + 4;
  const originZ = chunkZ * 16 + 4;
  const surface = context.surfaceY ? context.surfaceY(originX, originZ, 'world_surface_wg') : 70;
  const random = legacyFromLargeFeatureSeed(seed, chunkX, chunkZ);
  const params = { seed: random.nextInt() };
  const built = buildMansion(params);
  const template = new StructureTemplate(built, 'minecraft:mansion');
  const origin = { x: originX, y: surface, z: originZ };

  const start = new StructureStart({
    structureId: 'mansion',
    chunkX,
    chunkZ,
    pieces: [new StructurePiece({
      id: 'minecraft:mansion',
      index: 0,
      type: 'template',
      family: 'template',
      template: template.name,
      box: template.boundingBox(origin, 0),
      meta: { origin, params }
    })],
    biome: context.biomeAt ? context.biomeAt(originX, originZ) : null,
    seed
  });
  start.meta = {
    floors: MANSION_FLOORS,
    rooms: MANSION_GRID_CELLS * MANSION_FLOORS,
    roomTypes: built.meta.roomTypes,
    y: surface
  };
  return start;
}

export function realizeMansion(start, setBlock, blockIds, { spawnMob = null } = {}) {
  const resolver = createBlockIdResolver(blockIds || undefined);
  const piece = start.pieces[0];
  const template = new StructureTemplate(buildMansion(piece.meta.params), piece.template);
  const random = new LegacyRandom(BigInt(start.seed ?? 0) + BigInt(piece.index) * 2654435761n);
  const placement = placeTemplate({
    template,
    origin: piece.meta.origin,
    rotation: piece.rotation,
    mirror: piece.mirror,
    processors: { processors: [{ processor_type: 'minecraft:jigsaw_replacement' }] },
    random,
    world: null
  });

  const missingBlocks = new Set();
  const chests = [];
  const cells = new Set();
  let written = 0;
  for (const block of placement.blocks) {
    const id = resolver.resolveState(block.state);
    if (id === null) { missingBlocks.add(block.state.name); continue; }
    if (block.nbt?.LootTable) chests.push(block.nbt.LootTable);
    // PIECE-LOCAL coordinates, per deviation 0f: absolute coordinates carry the chunk offset and would inflate
    // the cell count beyond one floor's grid.
    const localX = block.x - piece.meta.origin.x;
    const localZ = block.z - piece.meta.origin.z;
    cells.add(Math.floor(localX / MANSION_ROOM_SIZE) + ':' + Math.floor(localZ / MANSION_ROOM_SIZE) + ':' + Math.floor((block.y - piece.meta.origin.y) / MANSION_ROOM_HEIGHT));
    if (setBlock(block.x, block.y, block.z, id, {
      state: block.state,
      ...(block.nbt?.LootTable ? { lootTable: block.nbt.LootTable } : {})
    })) written++;
  }

  const spawned = [];
  if (spawnMob) {
    for (const type of MANSION_INHABITANTS) {
      if (spawnMob(type, piece.meta.origin.x + 5.5, piece.meta.origin.y + 1, piece.meta.origin.z + 5.5, { persistent: true })) spawned.push(type);
    }
  }

  return {
    written,
    cells,
    chests: chests.length,
    chestLoot: chests,
    spawned,
    missingBlocks: [...missingBlocks].sort(),
    note: 'clean-room floor plan; inhabitants are a marker pair, because vanilla populates a mansion by spawn override'
  };
}
