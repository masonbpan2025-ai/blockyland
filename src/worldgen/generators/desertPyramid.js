// Desert pyramid: the first structure of the PROCEDURAL family, and the first with a trap.
//
// From the wiki (`Desert Pyramid`, 1.21.4 revision):
//   * a stepped sandstone pyramid, four levels, each smaller than the one below, with orange terracotta
//     decoration near the top and an entrance gap on one face;
//   * beneath it a hidden treasure room holding FOUR chests, each with a different loot table, and a stone
//     pressure plate over a pit of TNT -- step on it and the room explodes;
//   * the loot is `desert_pyramid` in `{{LootChest}}` terms, one chest being the "decorated" one;
//   * vanilla marks the structure `beard_thin`, so sand is meant to be shaved around it.
//
// PROVENANCE: no Minecraft assets. The pyramid is generated by code, not from a template -- but it is then
// represented AS a pseudo-template so that rotation, processors and realization reuse the one pipeline
// every other structure already uses. That is a deliberate choice: a second realization path for
// procedural structures would be a second place for chunk-clipping and determinism bugs to live.
//
// DEVIATIONS, recorded rather than hidden:
//   1. the wiki describes the pyramid's shape but not every dimension, so the levels, the treasure room's
//      size and the depth below the surface are a clean-room approximation of the described layout;
//   2. `beard_thin` terrain adaptation is NOT applied -- terrain shaping is a known missing subsystem
//      (STRUCTURE_ARCHITECTURE.md), so the pyramid sits on the surface height rather than being bedded
//      into the sand. This is visible in the Inspector as a floating edge on sloped ground;
//   3. the four chests carry the conventional loot-table ids, because the wiki publishes only the
//      `{{LootChest}}` keys.

import { StructurePiece, StructureStart } from '../start.js';
import { LegacyRandom, legacyFromLargeFeatureSeed } from '../random.js';
import { placeTemplate } from '../templatePlacement.js';
import { StructureTemplate } from '../template.js';
import { createBlockIdResolver } from '../blockIds.js';

/** The pyramid's base width. Four levels step in by two blocks each. */
export const PYRAMID_BASE = 21;
export const PYRAMID_LEVELS = 4;
/** The treasure room sits this far below the pyramid's base, and is this wide. */
export const TREASURE_DEPTH = 4;
export const TREASURE_WIDTH = 7;

/** The four chests, in the wiki's terms: one decorated, three plain. */
export const PYRAMID_CHESTS = [
  'minecraft:chests/desert_pyramid',
  'minecraft:chests/desert_pyramid',
  'minecraft:chests/desert_pyramid',
  'minecraft:chests/desert_pyramid_decorated'
];

/**
 * Build the pyramid and its treasure room as a pseudo-template.
 *
 * The layout is anchored so that y = PYRAMID_BASE_Y is the sand surface: the treasure room hangs below it,
 * which is why the caller places the origin at `surface - PYRAMID_BASE_Y`.
 */
export const PYRAMID_BASE_Y = TREASURE_DEPTH;

export function buildDesertPyramid({ seed = 0 } = {}) {
  const random = new LegacyRandom(BigInt(seed) * 2862933555777941757n + 3037000493n);
  const base = PYRAMID_BASE;
  const roomW = TREASURE_WIDTH;
  const sizeY = PYRAMID_BASE_Y + PYRAMID_LEVELS + 1;
  const size = [base, sizeY, base];
  const palette = [
    { Name: 'minecraft:air' },
    { Name: 'minecraft:sandstone' },
    { Name: 'minecraft:cut_sandstone' },
    { Name: 'minecraft:orange_terracotta' },
    { Name: 'minecraft:chest', Properties: { facing: 'north', waterlogged: 'false' } },
    { Name: 'minecraft:stone_pressure_plate' },
    { Name: 'minecraft:tnt' },
    { Name: 'minecraft:sandstone_stairs', Properties: { facing: 'north', half: 'bottom', shape: 'straight', waterlogged: 'false' } }
  ];
  const blocks = [];
  const set = (x, y, z, state) => {
    const [sx, sy, sz] = size;
    if (x >= 0 && x < sx && y >= 0 && y < sy && z >= 0 && z < sz) blocks.push({ pos: [x, y, z], state });
  };

  const mid = Math.floor(base / 2);
  const roomMin = mid - Math.floor(roomW / 2);
  const roomMax = roomMin + roomW - 1;

  // --- Treasure room, below the surface -------------------------------------------------------
  // A TNT pit under the floor's middle, with a pressure plate on top of it: the documented trap.
  for (let dx = -1; dx <= 1; dx++) {
    for (let dz = -1; dz <= 1; dz++) set(mid + dx, 0, mid + dz, 6);
  }
  for (let x = roomMin - 1; x <= roomMax + 1; x++) {
    for (let z = roomMin - 1; z <= roomMax + 1; z++) {
      // Floor, with a one-block hole above the plate so the trap is reachable but not obvious.
      set(x, 1, z, 1);
      set(x, PYRAMID_BASE_Y - 1, z, 1); // ceiling
    }
  }
  for (let y = 2; y <= PYRAMID_BASE_Y - 2; y++) {
    for (let x = roomMin - 1; x <= roomMax + 1; x++) {
      set(x, y, roomMin - 1, 1);
      set(x, y, roomMax + 1, 1);
    }
    for (let z = roomMin - 1; z <= roomMax + 1; z++) {
      set(roomMin - 1, y, z, 1);
      set(roomMax + 1, y, z, 1);
    }
  }
  set(mid, 1, mid, 5); // the pressure plate, directly above the TNT

  // The four chests, one in each corner of the room, each in a sandstone niche.
  const corners = [[roomMin, roomMin], [roomMin, roomMax], [roomMax, roomMin], [roomMax, roomMax]];
  corners.forEach(([x, z], index) => {
    blocks.push({
      pos: [x, 2, z],
      state: 4,
      nbt: { id: 'minecraft:chest', LootTable: PYRAMID_CHESTS[index], chestIndex: index }
    });
  });

  // --- Entrance: a shaft from the room up to a gap in the pyramid's north face ---------------
  const shaftX = mid;
  const shaftZ = roomMin - 1;
  for (let y = 2; y <= PYRAMID_BASE_Y; y++) set(shaftX, y, shaftZ, 0);
  // A gap in the base level's north wall, which is what makes the entrance hidden rather than obvious.
  set(shaftX, PYRAMID_BASE_Y, 0, 0);
  set(shaftX, PYRAMID_BASE_Y - 1, 0, 0);

  // --- The pyramid -----------------------------------------------------------------------------
  let width = base;
  let level = 0;
  while (width > 0 && level <= PYRAMID_LEVELS) {
    const min = Math.floor((base - width) / 2);
    const max = min + width - 1;
    for (let x = min; x <= max; x++) {
      for (let z = min; z <= max; z++) {
        const edge = x === min || x === max || z === min || z === max;
        const y = PYRAMID_BASE_Y + level;
        // Only the shell is drawn; the inside is solid sandstone on the first level and hollow above,
        // which leaves the corridor and the entrance shaft open.
        if (level === 0 || edge || width <= 5) set(x, y, z, 1);
        // Orange terracotta band near the top, as vanilla decorates it.
        if (level === PYRAMID_LEVELS - 1 && edge && ((x + z) % 5 === 0)) set(x, y, z, 3);
      }
    }
    width -= 4;
    level++;
  }
  // A cap so the top is closed, with the entrance corridor kept clear.
  const capMin = Math.floor(base / 2) - 1;
  for (let x = capMin; x <= capMin + 2; x++) for (let z = capMin; z <= capMin + 2; z++) set(x, sizeY - 1, z, 2);

  return { size, palette, blocks, entities: [], meta: { seed } };
}

export function generateDesertPyramid({ seed, chunkX, chunkZ, context }) {
  const originX = chunkX * 16 + 3;
  const originZ = chunkZ * 16 + 3;
  const surface = context.surfaceY ? context.surfaceY(originX, originZ, 'world_surface_wg') : 70;
  // The pseudo-template's y = PYRAMID_BASE_Y is the sand surface, so the origin sits that far below it.
  const y = surface - PYRAMID_BASE_Y;

  const random = legacyFromLargeFeatureSeed(seed, chunkX, chunkZ);
  const rotation = random.nextIntBound(4); // the entrance faces a random direction
  const params = { seed: random.nextInt() };
  const template = new StructureTemplate(buildDesertPyramid(params), 'minecraft:desert_pyramid');
  const piece = new StructurePiece({
    id: 'minecraft:desert_pyramid',
    type: 'template',
    family: 'hardcoded',
    template: template.name,
    rotation,
    box: template.boundingBox({ x: originX, y, z: originZ }, rotation),
    meta: { origin: { x: originX, y, z: originZ }, params }
  });

  const start = new StructureStart({
    structureId: 'desert_pyramid',
    chunkX,
    chunkZ,
    pieces: [piece],
    biome: context.biomeAt ? context.biomeAt(originX, originZ) : null,
    seed
  });
  start.meta = { rotation, surface, y, treasureY: surface - PYRAMID_BASE_Y + 1 };
  return start;
}

export function realizeDesertPyramid(start, setBlock, blockIds) {
  const resolver = createBlockIdResolver(blockIds || undefined);
  const piece = start.pieces[0];
  const template = new StructureTemplate(buildDesertPyramid(piece.meta.params), piece.template);
  const random = new LegacyRandom(BigInt(start.seed ?? 0) + BigInt(start.chunkX) * 40503n + BigInt(start.chunkZ));
  const placement = placeTemplate({
    template,
    origin: piece.meta.origin,
    rotation: piece.rotation,
    mirror: piece.mirror,
    processors: { processors: [{ processor_type: 'minecraft:jigsaw_replacement' }] },
    random,
    world: null
  });

  const missingBlocks = new Set();
  const chests = [];
  let written = 0;
  let trapParts = 0;
  let plateSeen = false;
  for (const block of placement.blocks) {
    const id = resolver.resolveState(block.state);
    if (id === null) { missingBlocks.add(block.state.name); continue; }
    const name = block.state.name;
    if (name === 'minecraft:chest' && block.nbt?.LootTable) chests.push(block.nbt.LootTable);
    if (name === 'minecraft:tnt') trapParts++;
    if (name === 'minecraft:stone_pressure_plate') plateSeen = true;
    if (setBlock(block.x, block.y, block.z, id, {
      state: block.state,
      ...(block.nbt?.LootTable ? { lootTable: block.nbt.LootTable } : {})
    })) written++;
  }

  return {
    written,
    chests,
    trap: { tnt: trapParts, pressurePlate: plateSeen, armed: trapParts > 0 && plateSeen },
    missingBlocks: [...missingBlocks].sort(),
    note: 'clean-room layout; beard_thin terrain adaptation is not applied'
  };
}
