// Ocean monument: a prismarine room graph on the deep ocean floor.
//
// From the wiki (`Ocean Monument`, 1.21.4 revision) and this repository's registry entry: deep oceans only; a
// large prismarine structure whose interior is a GRAPH OF ROOMS rather than one hall; three ELDER GUARDIANS;
// sponge rooms; dark prismarine and sea lanterns throughout; and a central treasure room holding GOLD BLOCKS.
//
// SCALE, recorded rather than hidden: vanilla's monument is a 58x58 room graph. Building that here would mean
// roughly 25,000 blocks per monument and would dominate the test suite's runtime, so this is a 23x23x13
// monument with the same STRUCTURE -- a 3x3 grid of rooms over three levels, dark prismarine on the upper
// level, sponge rooms below, and a gold-filled central room -- at reduced scale. The block count and the room
// count are therefore approximations; the composition, the placement and the content are not.
//
// PROVENANCE: no Minecraft assets. The plan is generated by code. The pseudo-template path is the same one the
// desert pyramid, the swamp hut, the End city and the jungle pyramid use, so realization reuses the single
// pipeline and stays chunk-safe.
//
// The elder guardians are placed as ENTITY MARKERS, because vanilla populates a monument through its own
// spawning rather than through structure blocks; the realization note records that rather than pretending three
// mobs make a monument dangerous.

import { StructurePiece, StructureStart } from '../start.js';
import { LegacyRandom, legacyFromLargeFeatureSeed } from '../random.js';
import { placeTemplate } from '../templatePlacement.js';
import { StructureTemplate } from '../template.js';
import { createBlockIdResolver } from '../blockIds.js';

export const MONUMENT_MATERIALS = {
  prismarine: 'minecraft:prismarine',
  bricks: 'minecraft:prismarine_bricks',
  dark: 'minecraft:dark_prismarine',
  lantern: 'minecraft:sea_lantern',
  slab: 'minecraft:prismarine_slab',
  stairs: 'minecraft:prismarine_stairs',
  sponge: 'minecraft:wet_sponge',
  drySponge: 'minecraft:sponge',
  gold: 'minecraft:gold_block'
};

export const MONUMENT_LEVELS = 3;
export const MONUMENT_GRID = 3;
export const MONUMENT_ROOM = 7;
export const MONUMENT_ROOM_HEIGHT = 4;
export const MONUMENT_WIDTH = MONUMENT_GRID * MONUMENT_ROOM + 2;
/** The central room holds this many gold blocks, as the wiki describes. */
export const MONUMENT_GOLD = 8;
/** Three elder guardians, as the wiki describes. */
export const MONUMENT_ELDER_COUNT = 3;

export function buildMonument({ seed = 0 } = {}) {
  const random = new LegacyRandom(BigInt(seed) * 6364136223846793005n + 1442695040888963407n);
  const width = MONUMENT_WIDTH;
  const height = MONUMENT_LEVELS * MONUMENT_ROOM_HEIGHT + 1;
  const size = [width, height, width];
  const palette = [{ Name: 'minecraft:air' }];
  const index = new Map();
  const material = (name) => {
    if (!index.has(name)) { index.set(name, palette.length); palette.push({ Name: name }); }
    return index.get(name);
  };
  const blocks = [];
  // A block outside the declared size would be written outside the piece box: a plan whose advertised box is a
  // lie, and a chunk-clipping hazard. It is an error, not a silent extra block.
  const push = (x, y, z, state) => {
    if (x < 0 || y < 0 || z < 0 || x >= width || y >= height || z >= width) {
      throw new Error('monument: block ' + x + ',' + y + ',' + z + ' is outside ' + size.join('x'));
    }
    blocks.push({ pos: [x, y, z], state });
  };
  const m = (key) => material(MONUMENT_MATERIALS[key]);
  const mid = Math.floor(width / 2);

  // --- The shell ---------------------------------------------------------------------------------
  for (let x = 0; x < width; x++) {
    for (let z = 0; z < width; z++) {
      const edge = x === 0 || x === width - 1 || z === 0 || z === width - 1;
      push(x, 0, z, m('bricks'));
      push(x, height - 1, z, m('slab'));
      for (let y = 1; y < height - 1; y++) {
        if (!edge) continue;
        // Sea lanterns light the shell in a regular pattern, which is what makes a monument visible underwater.
        const lit = (x + z + y) % 5 === 0 || (y % 3 === 0 && (x % 4 === 0 || z % 4 === 0));
        push(x, y, z, lit ? m('lantern') : m('prismarine'));
      }
    }
  }

  // --- Three levels of a 3x3 room grid ------------------------------------------------------------
  for (let level = 0; level < MONUMENT_LEVELS; level++) {
    const base = level * MONUMENT_ROOM_HEIGHT;
    for (let rx = 0; rx < MONUMENT_GRID; rx++) {
      for (let rz = 0; rz < MONUMENT_GRID; rz++) {
        const x0 = 1 + rx * MONUMENT_ROOM;
        const z0 = 1 + rz * MONUMENT_ROOM;
        const centre = level === 1 && rx === 1 && rz === 1;
        const spongeRoom = level === 0 && (rx + rz) % 2 === 0 && !(rx === 1 && rz === 1);
        for (let x = 0; x < MONUMENT_ROOM; x++) {
          for (let z = 0; z < MONUMENT_ROOM; z++) {
            // Floor and ceiling for the room; the ceiling of a level is the next level's floor.
            push(x0 + x, base, z0 + z, level === MONUMENT_LEVELS - 1 ? m('dark') : m('bricks'));
            if (base + MONUMENT_ROOM_HEIGHT < height) push(x0 + x, base + MONUMENT_ROOM_HEIGHT, z0 + z, m('bricks'));
            for (let y = 1; y < MONUMENT_ROOM_HEIGHT; y++) {
              const wall = x === 0 || x === MONUMENT_ROOM - 1 || z === 0 || z === MONUMENT_ROOM - 1;
              if (!wall) continue;
              // DOORWAYS between rooms on two sides, so the grid is a room GRAPH rather than sealed cells.
              const doorway = z === 0 && x === 3 && y <= 2;
              if (doorway) continue;
              push(x0 + x, base + y, z0 + z, spongeRoom && y === 1 ? m('sponge') : m('prismarine'));
            }
          }
        }
        // The central treasure room: gold blocks around a sea lantern, the monument's prize.
        if (centre) {
          const cx = x0 + 3;
          const cz = z0 + 3;
          push(cx, base + 1, cz, m('lantern'));
          for (const [dx, dz] of [[-2, -2], [-2, 2], [2, -2], [2, 2], [-2, 0], [2, 0], [0, -2], [0, 2]]) {
            push(cx + dx, base + 1, cz + dz, m('gold'));
          }
        }
        // Sponge rooms hold the monument's sponges, wet and dry, which is their documented content.
        if (spongeRoom) {
          push(x0 + 1, base + 1, z0 + 1, m('wetSponge'));
          push(x0 + MONUMENT_ROOM - 2, base + 1, z0 + MONUMENT_ROOM - 2, m('drySponge'));
        }
      }
    }
  }

  // --- The entrance: a doorway in the shell, so the monument is enterable ---------------------------------
  push(mid, 1, 0, m('prismarine'));
  push(mid, 2, 0, m('prismarine'));

  return {
    size,
    palette,
    blocks,
    entities: [],
    meta: {
      levels: MONUMENT_LEVELS,
      rooms: MONUMENT_GRID * MONUMENT_GRID * MONUMENT_LEVELS,
      gold: MONUMENT_GOLD,
      scale: 'reduced from vanilla 58x58; see the file header'
    }
  };
}

export function generateMonument({ seed, chunkX, chunkZ, context }) {
  const originX = chunkX * 16 + 6;
  const originZ = chunkZ * 16 + 6;
  // On the ocean floor, which is why it is built at the floor height rather than at the surface.
  const floor = context.surfaceY ? context.surfaceY(originX, originZ, 'ocean_floor_wg') : 40;
  const random = legacyFromLargeFeatureSeed(seed, chunkX, chunkZ);
  const params = { seed: random.nextInt() };
  const template = new StructureTemplate(buildMonument(params), 'minecraft:ocean_monument');

  const start = new StructureStart({
    structureId: 'monument',
    chunkX,
    chunkZ,
    pieces: [new StructurePiece({
      id: 'minecraft:ocean_monument',
      index: 0,
      type: 'template',
      family: 'procedural',
      template: template.name,
      box: template.boundingBox({ x: originX, y: floor, z: originZ }, 0),
      meta: { origin: { x: originX, y: floor, z: originZ }, params }
    })],
    biome: context.biomeAt ? context.biomeAt(originX, originZ) : null,
    seed
  });
  start.meta = { floor, floors: MONUMENT_LEVELS, rooms: MONUMENT_GRID * MONUMENT_GRID * MONUMENT_LEVELS };
  return start;
}

export function realizeMonument(start, setBlock, blockIds, { spawnMob = null } = {}) {
  const resolver = createBlockIdResolver(blockIds || undefined);
  const piece = start.pieces[0];
  const template = new StructureTemplate(buildMonument(piece.meta.params), piece.template);
  const random = new LegacyRandom(BigInt(start.seed ?? 0) + BigInt(piece.index) * 2654435761n);
  const placement = placeTemplate({
    template,
    origin: piece.meta.origin,
    rotation: piece.rotation,
    mirror: piece.mirror,
    processors: { processors: [{ processor_type: 'minecraft:jigsaw_replacement' }] },
    random,
    world: null
  });

  const missingBlocks = new Set();
  const counts = { gold: 0, lantern: 0, sponge: 0, dark: 0 };
  let written = 0;
  for (const block of placement.blocks) {
    const id = resolver.resolveState(block.state);
    if (id === null) { missingBlocks.add(block.state.name); continue; }
    const name = block.state.name;
    if (name === MONUMENT_MATERIALS.gold) counts.gold++;
    else if (name === MONUMENT_MATERIALS.lantern) counts.lantern++;
    else if (name === MONUMENT_MATERIALS.sponge || name === MONUMENT_MATERIALS.drySponge) counts.sponge++;
    else if (name === MONUMENT_MATERIALS.dark) counts.dark++;
    if (setBlock(block.x, block.y, block.z, id, { state: block.state })) written++;
  }

  const spawned = [];
  if (spawnMob) {
    // THREE elder guardians, placed as markers at the monument's three levels.
    const origin = piece.meta.origin;
    for (let i = 0; i < MONUMENT_ELDER_COUNT; i++) {
      if (spawnMob('elder_guardian', origin.x + 11.5, origin.y + 1 + i * MONUMENT_ROOM_HEIGHT, origin.z + 11.5, { persistent: true })) {
        spawned.push('elder_guardian');
      }
    }
  }

  return {
    written,
    counts,
    spawned,
    missingBlocks: [...missingBlocks].sort(),
    note: 'room graph at reduced scale; elder guardians are markers, because vanilla populates a monument by its own spawning'
  };
}
