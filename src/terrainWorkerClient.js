import { createTerrainService } from './terrainService.js';

/**
 * Terrain generation on a worker thread, so walking into new land does not stall the frame.
 *
 * Why. Crossing a chunk border at render distance 8 brings about nineteen new chunks into range, and each was
 * generated whole, on the main thread, in one frame: 20-50ms apiece on a laptop, so every border was a run of
 * slow frames. Generation is a pure function of the seed, the settings and the chunk's coordinates (no chunk
 * reads or writes another -- tests/terrainWorker.test.js), so a copy of the world on another thread can do it.
 *
 * How:
 *   1. The worker builds a copy of the world: the same seed, biome choice, data packs and structure list.
 *   2. Before it is trusted, it is CHECKED. The first chunks the game generates itself afterwards are recorded
 *      (World.generationProbe), the worker generates the same chunks, and everything must match: voxels, water,
 *      orientations, the structures' requests, loot. A mod, a pack or a setting the copy did not reproduce
 *      shows up here, and the game then keeps generating on the main thread. It never adopts a chunk from a
 *      worker that disagreed with it.
 *   3. Once checked, the streamer asks it for chunks and adopts what comes back (World.adoptGeneratedChunk), which
 *      costs a copy plus the same water, light and population tail as before -- not the generation.
 *
 * Only plain Overworld terrain goes to the worker. The Nether, the End, authored and flat worlds, the start
 * village chunk and worlds with /fillbiome overrides are generated by the game as before.
 */
export class TerrainWorkerClient {
  /**
   * @param {object} options
   * @param {(onMessage: (message: object) => void) => ({post: Function, terminate: Function}|null)} options.connect
   * @param {number} [options.maxInFlight] chunks asked for at once; few, so requests follow the player
   * @param {number} [options.probes] chunks checked against the game before the worker is used
   */
  constructor({ connect, maxInFlight = 3, probes = 2, log = console } = {}) {
    this.connect = connect;
    this.maxInFlight = maxInFlight;
    this.probes = probes;
    this.log = log;
    this.enabled = true;
    /** 'idle' | 'off' | 'starting' | 'validating' | 'ready' | 'failed' */
    this.state = 'idle';
    this.failure = null;
    this.epoch = 0;
    this.nextId = 0;
    this.connection = null;
    this.world = null;
    this.structures = null;
    this.packs = null;
    this.workerReady = false;
    this.probeList = [];
    this.probesPassed = 0;
    this.probe = null;
    /** id -> { key, probe? } */
    this.inFlight = new Map();
    /** Chunks asked for and not yet adopted or dropped, so the streamer does not ask twice. */
    this.pendingKeys = new Set();
    this.results = [];
    this.stats = { requested: 0, received: 0, workerMs: 0, validated: 0 };
  }

  /** A client backed by a real module worker, or null where the browser has none. */
  static forBrowser(options = {}) {
    if (typeof Worker === 'undefined') return null;
    return new TerrainWorkerClient({
      ...options,
      connect: (onMessage) => {
        const worker = new Worker(new URL('./terrainWorker.js', import.meta.url), { type: 'module' });
        worker.onmessage = (event) => onMessage(event.data);
        worker.onerror = (event) => { event.preventDefault?.(); onMessage({ type: 'error', message: event.message || 'the terrain worker failed to load' }); };
        worker.onmessageerror = () => onMessage({ type: 'error', message: 'a terrain worker message could not be read' });
        return { post: (message, transfer) => worker.postMessage(message, transfer ?? []), terminate: () => worker.terminate() };
      },
    });
  }

  /** A client whose "worker" runs in this thread, answering asynchronously as a worker would. For tests. */
  static inProcess(options = {}) {
    return new TerrainWorkerClient({
      ...options,
      connect: (onMessage) => {
        const service = createTerrainService({ sharedRealm: true });
        let alive = true;
        return {
          post: (message) => setTimeout(() => {
            if (!alive) return;
            const { reply } = service.handle(structuredClone(message));
            if (alive) onMessage(structuredClone(reply));
          }, 0),
          terminate: () => { alive = false; },
        };
      },
    });
  }

  setEnabled(enabled) {
    this.enabled = enabled !== false;
    if (!this.enabled) { this.stop(); this.state = 'off'; this.world = null; }
  }

  /**
   * Follow the game's world. Called by the streamer every update; starts a worker for a new world, a reseed or a
   * different set of data packs, and otherwise does nothing.
   */
  sync(game) {
    if (!this.enabled || !game?.worldReady || !game.world) return;
    this.prepare(game);
  }

  /**
   * Start for the game's world now, if not already started for it. The game calls this as a new world begins
   * loading, once its data packs and structure engine are in place: the chunks the loading screen generates then
   * serve as the check, and play starts with the worker already trusted.
   */
  prepare(game) {
    if (!this.enabled || !game?.world) return;
    const world = game.world;
    if (this.world === world && this.structures === world.structures && this.packs === (game.dataPackApplication ?? null)) return;
    this.start(game);
  }

  start(game) {
    this.stop();
    const world = game.world;
    this.world = world;
    this.structures = world.structures;
    this.packs = game.dataPackApplication ?? null;
    this.failure = null;
    if (world.generationMode !== 'procedural' || world.isFlatWorld || !world.structures?.realizedKeysFor) { this.state = 'off'; return; }
    this.epoch++;
    this.state = 'starting';
    this.workerReady = false;
    this.probeList = [];
    this.probesPassed = 0;
    let connection = null;
    try { connection = this.connect((message) => this.receive(message)); } catch (err) { this.fail(`could not start: ${err?.message || err}`); return; }
    if (!connection) { this.fail('could not start'); return; }
    this.connection = connection;
    const probe = {
      accept: (w, cx, cz) => this.probeList.length < this.probes && this.eligible(w, cx, cz),
      add: (record) => {
        this.probeList.push(record);
        if (this.probeList.length >= this.probes && world.generationProbe === probe) world.generationProbe = null;
        this.maybeValidate();
      },
    };
    this.probe = probe;
    world.generationProbe = probe;
    try {
      this.connection.post({ type: 'init', epoch: this.epoch, config: TerrainWorkerClient.configFor(game) });
    } catch (err) {
      this.fail(`could not send the world to the worker: ${err?.message || err}`);
    }
  }

  /** What the worker needs to build the same world. */
  static configFor(game) {
    const world = game.world;
    return {
      seed: world.seed,
      selectedBiome: world.selectedBiome,
      seaLevel: world.seaLevel,
      enabledIds: world.structures?.enabledIds ?? null,
      packs: (game.dataPackApplication?.applied ?? []).map(({ pack }) => ({ name: pack.name, files: pack.files, format: pack.format, source: pack.source })),
    };
  }

  stop() {
    this.connection?.terminate();
    this.connection = null;
    if (this.world && this.world.generationProbe === this.probe) this.world.generationProbe = null;
    this.probe = null;
    this.inFlight.clear();
    this.pendingKeys.clear();
    this.results = [];
    if (this.state !== 'failed' && this.state !== 'off') this.state = 'idle';
  }

  fail(reason) {
    this.failure = reason;
    this.log?.warn?.(`[Terrain worker] ${reason}. New terrain is generated on the main thread instead.`);
    this.stop();
    this.state = 'failed';
  }

  /** Can this chunk of this world come from the worker? */
  eligible(world, cx, cz) {
    return world === this.world && world.structures === this.structures
      && world.generationMode === 'procedural' && !world.isFlatWorld && !world.isNether
      && world.dimension === 'overworld' && (world.currentDimension ?? 'overworld') === 'overworld'
      && !(cx === 0 && cz === 0) // the start village is placed by the game itself (World.generateVillage)
      && !(world.biomeOverrides?.size > 0) && !(world.floorY > -Infinity);
  }

  canGenerate(world, cx, cz) {
    return this.enabled && this.state === 'ready' && this.eligible(world, cx, cz);
  }

  isPending(cx, cz) {
    return this.pendingKeys.has(`${cx},${cz}`);
  }

  /** Ask for a chunk. False when enough are already being made. */
  request(world, cx, cz) {
    if (!this.canGenerate(world, cx, cz) || this.inFlight.size >= this.maxInFlight || this.isPending(cx, cz)) return false;
    const id = ++this.nextId;
    const key = `${cx},${cz}`;
    this.inFlight.set(id, { key });
    this.pendingKeys.add(key);
    this.stats.requested++;
    this.connection.post({ type: 'generate', epoch: this.epoch, id, cx, cz,
      appliedKeys: world.structures.appliedKeysFor(cx, cz), realizedKeys: world.structures.realizedKeysFor(cx, cz) });
    return true;
  }

  hasResult() {
    return this.results.length > 0;
  }

  /** The next finished chunk, for World.adoptGeneratedChunk. */
  takeResult() {
    const result = this.results.shift();
    if (result) this.pendingKeys.delete(`${result.cx},${result.cz}`);
    return result ?? null;
  }

  receive(message) {
    if (message?.epoch !== undefined && message.epoch !== this.epoch) return; // from a worker since replaced
    if (message?.type === 'ready') { this.workerReady = true; this.maybeValidate(); return; }
    if (message?.type === 'error') { this.fail(message.message || 'the worker reported an error'); return; }
    if (message?.type !== 'chunk') return;
    const job = this.inFlight.get(message.id);
    if (!job) return;
    this.inFlight.delete(message.id);
    this.stats.received++;
    this.stats.workerMs += message.result?.ms ?? 0;
    if (job.probe) { this.checkProbe(job.probe, message.result); return; }
    this.results.push(message.result);
  }

  /** Once the worker is up and the game has recorded its probe chunks, have the worker make the same chunks. */
  maybeValidate() {
    if (!this.workerReady || this.state !== 'starting' || this.probeList.length < this.probes) return;
    this.state = 'validating';
    for (const probe of this.probeList) {
      const id = ++this.nextId;
      this.inFlight.set(id, { key: `${probe.cx},${probe.cz}`, probe });
      this.connection.post({ type: 'generate', epoch: this.epoch, id, cx: probe.cx, cz: probe.cz, appliedKeys: probe.appliedBefore, realizedKeys: probe.realizedBefore });
    }
  }

  checkProbe(probe, result) {
    const difference = generationDifference(probe, result);
    if (difference) { this.fail(`disagrees with the game about chunk ${probe.cx},${probe.cz} (${difference})`); return; }
    this.probesPassed++;
    if (this.probesPassed >= this.probeList.length) {
      this.state = 'ready';
      this.stats.validated++;
      this.probeList = [];
    }
  }
}

/** Where two records of generating the same chunk differ, or null when they are the same. */
export function generationDifference(a, b) {
  if (!b) return 'no result';
  if (a.unrecordable || b.unrecordable) return 'generation did something that could not be recorded';
  if (a.cx !== b.cx || a.cz !== b.cz) return 'different chunk';
  if (!sameArray(a.voxels, b.voxels)) return 'blocks';
  if (!sameArray(a.waterLevels, b.waterLevels)) return 'water levels';
  if ((a.weatherRevision ?? 0) !== (b.weatherRevision ?? 0)) return 'block writes';
  if (JSON.stringify(a.ops) !== JSON.stringify(b.ops)) return 'orientations or structure requests';
  if (JSON.stringify(a.loot) !== JSON.stringify(b.loot)) return 'loot';
  if (JSON.stringify(a.appliedKeys) !== JSON.stringify(b.appliedKeys)) return 'structures placed';
  if (JSON.stringify(a.stats) !== JSON.stringify(b.stats)) return 'structure counts';
  return null;
}

function sameArray(a, b) {
  if (!a || !b || a.length !== b.length) return false;
  for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) return false;
  return true;
}
