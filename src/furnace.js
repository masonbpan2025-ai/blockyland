// Vanilla smelting and fuel entries this table was missing, plus per-recipe experience.
//
// Generated by scripts/generate-smelting.mjs from Mineclonia's cooking and fuel declarations, because
// minecraft-data publishes no smelting data. Merged by mutation so existing references keep working,
// and guarded so a generated entry can never silently replace a hand-tuned one.
for (const [key, value] of Object.entries(EXTRA_SMELTING)) {
  const k = /^[0-9]+$/.test(key) ? Number(key) : key;
  if (SMELTING_RECIPES[k] !== undefined) {
    throw new Error(`extraSmelting collision on '${key}'; hand-written smelting must win`);
  }
  SMELTING_RECIPES[k] = { id: value.id, isBlock: value.isBlock, count: value.count };
}
// The fuel merge deliberately sits AFTER the FUEL_BURN_TIMES declaration below: `const` bindings are
// in a temporal dead zone until their initialiser runs, so merging here would throw at import time.

/**
 * Smelting experience for an output, per recipe.
 *
 * Vanilla varies this per item -- 0.1 for food, 0.7 for iron, 1.0 for gold and diamond -- and
 * Mineclonia gives a flat 1 with a source comment admitting it is a TODO. The values here are
 * vanilla's, and anything without a specific entry falls back to the food default.
 *
 * The table is keyed by NAME, but a smelting output for a block carries a numeric id, so the id is
 * resolved through BLOCK_DEFS first. Looking the numeric id up directly found nothing and silently
 * returned the default for every block, which is the kind of bug that looks like "XP is 0.1 for
 * everything" rather than a lookup failure.
 */
export function getSmeltingXp(output) {
  if (!output) return DEFAULT_SMELTING_XP;
  const key = output.isBlock ? blockNameForXp(output.id) : output.id;
  if (key && SMELTING_XP[key] !== undefined) return SMELTING_XP[key];
  return DEFAULT_SMELTING_XP;
}

/** Normalise a block id to the snake_case name the XP table is keyed by. */
function blockNameForXp(id) {
  const def = BLOCK_DEFS[id];
  if (!def?.name) return undefined;
  return String(def.name).toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
}

