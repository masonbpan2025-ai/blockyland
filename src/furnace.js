// Smelting and fuel for blocks that are not registered yet.
//
// These cannot be written as `[BLOCKS.DEEPSLATE_IRON_ORE]: {...}` in the tables above. Where the
// constant is undefined that idiom does not create a dead entry -- it creates an entry keyed
// "undefined", so five unregistered ores and one unregistered sapling produced two phantom rows, and
// the last ore won: `getSmeltingRecipe('undefined')` returned a copper ingot.
//
// Listed by name instead, so the entry appears by itself once the block exists and nothing is written
// under a name no item can hold. `node scripts/inspect-resource.mjs faults` reports the idiom anywhere
// in `src/`, which is how these six were found.
const PENDING_ORE_SMELTING = [
  ['DEEPSLATE_IRON_ORE', 'iron_ingot'],
  ['DEEPSLATE_GOLD_ORE', 'gold_ingot'],
  ['NETHER_GOLD_ORE', 'gold_ingot'],
  ['COPPER_ORE', 'copper_ingot'],
  ['DEEPSLATE_COPPER_ORE', 'copper_ingot'],
  // Ancient debris is the first link of the netherite chain and the only source of netherite scrap in
  // vanilla, and nothing smelted it. Four scrap and four gold make the ingot, so with this missing the
  // whole chain was dead: the ingot was uncraftable, and the smithing table had nothing to consume.
  ['ANCIENT_DEBRIS', 'netherite_scrap'],
];
for (const [blockName, output] of PENDING_ORE_SMELTING) {
  const blockId = BLOCKS[blockName];
  if (typeof blockId === 'number' && SMELTING_RECIPES[blockId] === undefined) {
    SMELTING_RECIPES[blockId] = { id: output, isBlock: false, count: 1 };
  }
}
{
  const sapling = BLOCKS.OAK_SAPLING;
  if (typeof sapling === 'number' && FUEL_BURN_TIMES[sapling] === undefined) FUEL_BURN_TIMES[sapling] = 5.0;
}

export function getSmeltingRecipe(item) {
  if (!item) return null;
  const id = typeof item === 'object' ? item.id : item;
  const recipe = SMELTING_RECIPES[id];
  return recipe ? { ...recipe } : null;
}

export function getFuelBurnTime(item) {
  if (!item) return 0;
  const id = typeof item === 'object' ? item.id : item;
  return FUEL_BURN_TIMES[id] || 0;
}

export class FurnaceManager {
  constructor(game) {
    this.game = game;
    this.furnaces = new Map(); // key `${x},${y},${z}` -> furnaceData
    this.openFurnaceKey = null;
  }

  getKey(x, y, z) {
    return `${Math.floor(x)},${Math.floor(y)},${Math.floor(z)}`;
  }

  getFurnace(x, y, z) {
    return this.furnaces.get(this.getKey(x, y, z)) || null;
  }

  getOrCreateFurnace(x, y, z) {
    const key = this.getKey(x, y, z);
    let furnace = this.furnaces.get(key);
    if (!furnace) {
      furnace = {
        x: Math.floor(x),
        y: Math.floor(y),
        z: Math.floor(z),
        input: null,
        fuel: null,
        output: null,
        burnTime: 0,
        maxBurnTime: 0,
        cookTime: 0,
        cookDuration: COOK_DURATION,
        lit: false,
        pointLight: null
      };
      this.furnaces.set(key, furnace);
    }
    return furnace;
  }

  openFurnaceAt(x, y, z) {
    const furnace = this.getOrCreateFurnace(x, y, z);
    this.openFurnaceKey = this.getKey(x, y, z);
    return furnace;
  }

  getOpenFurnace() {
    if (!this.openFurnaceKey) return null;
    return this.furnaces.get(this.openFurnaceKey) || null;
  }

  closeOpenFurnace() {
    this.openFurnaceKey = null;
  }

  addItem(x, y, z, id, isBlock = false, count = 1, slotType = 'input') {
    const furnace = this.getOrCreateFurnace(x, y, z);
    if (!furnace) return false;
    // A furnace slot holds a stack of the item, so the limit is the item's own: 64 for coal, one for a
    // lava bucket. A literal 64 let a slot hold sixty-four of something unstackable.
    const limit = stackLimitFor(id);

    if (slotType === 'fuel') {
      if (getFuelBurnTime(id) <= 0 && (!furnace.fuel || furnace.fuel.id !== id)) {
        return false;
      }
      if (!furnace.fuel) {
        furnace.fuel = { id, isBlock, count: Math.min(count, limit) };
        return true;
      } else if (furnace.fuel.id === id && !!furnace.fuel.isBlock === !!isBlock && furnace.fuel.count < limit) {
        const canAdd = Math.min(count, limit - furnace.fuel.count);
        furnace.fuel.count += canAdd;
        return true;
      }
      return false;
    } else {
      if (!furnace.input) {
        furnace.input = { id, isBlock, count: Math.min(count, limit) };
        return true;
      } else if (furnace.input.id === id && !!furnace.input.isBlock === !!isBlock && furnace.input.count < limit) {
        const canAdd = Math.min(count, limit - furnace.input.count);
        furnace.input.count += canAdd;
        return true;
      }
      return false;
    }
  }

  extractItem(x, y, z, slotType = 'output') {
    const furnace = this.getFurnace(x, y, z);
    if (!furnace) return null;

    const target = slotType === 'output' ? furnace.output : (slotType === 'fuel' ? furnace.fuel : furnace.input);
    if (target && target.count > 0) {
      const extracted = { id: target.id, isBlock: target.isBlock, count: 1 };
      target.count--;
      if (target.count <= 0) {
        if (slotType === 'output') furnace.output = null;
        else if (slotType === 'fuel') furnace.fuel = null;
        else furnace.input = null;
      }
      return extracted;
    }
    return null;
  }

  getRedstoneSignal(x, y, z) {
    const furnace = this.getFurnace(x, y, z);
    if (!furnace) return 0;
    const slots = [furnace.input, furnace.fuel, furnace.output];
    let totalItems = 0;
    let hasAny = false;
    for (const s of slots) {
      if (s && s.count > 0) {
        hasAny = true;
        totalItems += s.count;
      }
    }
    if (!hasAny) return 0;
    return Math.min(15, Math.floor(1 + (totalItems / (3 * 64)) * 14));
  }

  onBlockBroken(x, y, z) {
    const key = this.getKey(x, y, z);
    const furnace = this.furnaces.get(key);
    if (!furnace) return;

    // Remove PointLight if present
    if (furnace.pointLight) {
      this.game.scene.remove(furnace.pointLight);
      furnace.pointLight.dispose?.();
      furnace.pointLight = null;
    }

    // Drop any items contained inside furnace
    const dropItem = (item) => {
      if (item && item.count > 0) {
        this.game.entities.spawnDroppedItem(
          new THREE.Vector3(x + 0.5, y + 0.5, z + 0.5),
          item.id,
          item.isBlock,
          item.count
        );
      }
    };

    dropItem(furnace.input);
    dropItem(furnace.fuel);
    dropItem(furnace.output);

    this.furnaces.delete(key);
    if (this.openFurnaceKey === key) {
      this.closeOpenFurnace();
      this.game.ui.closeFurnaceModal();
    }
  }

  update(dt) {
    dt = Math.min(dt, 0.2);
    let updatedActiveGui = false;

    for (const [key, furnace] of this.furnaces.entries()) {
      const { x, y, z } = furnace;

      // 1. Progress active burn time
      if (furnace.burnTime > 0) {
        furnace.burnTime = Math.max(0, furnace.burnTime - dt);
      }

      // 2. Cooking check
      const recipe = getSmeltingRecipe(furnace.input);
      const canOutput = recipe && (
        !furnace.output ||
        (furnace.output.id === recipe.id &&
          furnace.output.isBlock === recipe.isBlock &&
          furnace.output.count + recipe.count <= 64)
      );

      if (recipe && canOutput) {
        // Need fuel burn time
        if (furnace.burnTime <= 0) {
          const fuelTime = getFuelBurnTime(furnace.fuel);
          if (fuelTime > 0) {
            furnace.burnTime = fuelTime;
            furnace.maxBurnTime = fuelTime;

            // Consume 1 fuel
            if (furnace.fuel.id === 'lava_bucket') {
              if (furnace.fuel.count <= 1) {
                furnace.fuel = { id: 'bucket', isBlock: false, count: 1 };
              } else {
                furnace.fuel.count--;
                this.game.inventory.addItem('bucket', false, 1);
              }
            } else {
              furnace.fuel.count--;
              if (furnace.fuel.count <= 0) furnace.fuel = null;
            }
          }
        }

        // Cook if actively burning
        if (furnace.burnTime > 0) {
          furnace.cookTime += dt;
          if (furnace.cookTime >= furnace.cookDuration - 0.0001) {
            furnace.cookTime = Math.max(0, furnace.cookTime - furnace.cookDuration);

            // Decrement input
            furnace.input.count--;
            if (furnace.input.count <= 0) furnace.input = null;

            // Add output
            if (!furnace.output) {
              furnace.output = { ...recipe };
            } else {
              furnace.output.count += recipe.count;
            }

            if (this.game.sounds) this.game.sounds.playPop();
          }
        } else {
          // No fuel active: cook progress resets or slowly decays
          furnace.cookTime = Math.max(0, furnace.cookTime - dt * 2.0);
        }
      } else {
        // Can't cook or no input
        furnace.cookTime = Math.max(0, furnace.cookTime - dt * 2.0);
      }

      // Reset maxBurnTime if burn finishes
      if (furnace.burnTime <= 0) {
        furnace.burnTime = 0;
        furnace.maxBurnTime = 0;
      }

      // 3. Lit state check & world block transformation
      const shouldBeLit = furnace.burnTime > 0;
      if (shouldBeLit !== furnace.lit) {
        furnace.lit = shouldBeLit;
        const currentVoxel = this.game.world.getVoxel(x, y, z);

        if (furnace.lit && currentVoxel === BLOCKS.FURNACE) {
          this.game.world.setVoxel(x, y, z, BLOCKS.LIT_FURNACE);
          this.rebuildBlockChunk(x, z);

          // Add dynamic warm fire PointLight
          if (!furnace.pointLight && this.game.scene) {
            const light = new THREE.PointLight(0xff983d, 1.8, 8);
            light.position.set(x + 0.5, y + 0.5, z + 0.5);
            this.game.scene.add(light);
            furnace.pointLight = light;
          }
        } else if (!furnace.lit && currentVoxel === BLOCKS.LIT_FURNACE) {
          this.game.world.setVoxel(x, y, z, BLOCKS.FURNACE);
          this.rebuildBlockChunk(x, z);

          // Remove PointLight
          if (furnace.pointLight && this.game.scene) {
            this.game.scene.remove(furnace.pointLight);
            furnace.pointLight.dispose?.();
            furnace.pointLight = null;
          }
        }
      }

      // 4. Lit effects (Particles, fire lighting flicker, crackle sound)
      if (furnace.lit) {
        // Spawn sparks and smoke particles around furnace
        if (this.game.entities?.spawnFurnaceParticles) {
          this.game.entities.spawnFurnaceParticles(new THREE.Vector3(x + 0.5, y + 0.5, z + 0.5));
        }

        // Firelight flicker
        if (furnace.pointLight) {
          furnace.pointLight.intensity = 1.7 + Math.sin(Date.now() * 0.018 + (x * 7 + z * 3)) * 0.3 + (Math.random() - 0.5) * 0.15;
        }

        // Occasional crackle sound if player is nearby
        if (this.game.sounds?.playFurnaceCrackle && Math.random() < 0.02) {
          const pPos = this.game.player?.position;
          if (pPos && pPos.distanceTo(new THREE.Vector3(x, y, z)) < 16) {
            this.game.sounds.playFurnaceCrackle();
          }
        }
      }

      // Check if this is the open furnace in GUI
      if (this.openFurnaceKey === key) {
        updatedActiveGui = true;
      }
    }

    if (updatedActiveGui && this.game.ui?.updateFurnaceProgress) {
      const openFurnace = this.getOpenFurnace();
      if (openFurnace) {
        this.game.ui.updateFurnaceProgress(openFurnace);
      }
    }
  }

  rebuildBlockChunk(x, z) {
    if (!this.game) return;
    const cx = Math.floor(x / 16);
    const cz = Math.floor(z / 16);
    const chunk = this.game.world?.getChunk(cx, cz);
    if (chunk && typeof this.game.rebuildChunkMesh === 'function') {
      this.game.rebuildChunkMesh(chunk);
    }
  }
}
