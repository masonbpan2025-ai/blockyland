/** A structure with the features every format has to preserve: properties, a gap, a block entity, an entity. */
function sampleStructure() {
  return new CanonicalStructure({
    name: 'io-test-house',
    regions: [new CanonicalRegion({
      name: 'main',
      origin: { x: 4, y: 5, z: 6 },
      size: { x: 3, y: 2, z: 3 },
      blocks: [
        { pos: { x: 0, y: 0, z: 0 }, state: state('stone') },
        { pos: { x: 1, y: 0, z: 0 }, state: state('oak_stairs', { facing: 'north', half: 'bottom', waterlogged: 'false' }) },
        { pos: { x: 2, y: 0, z: 2 }, state: state('chest', { facing: 'south' }), nbt: { id: 'minecraft:chest', LootTable: 'minecraft:chests/simple_dungeon' } },
        { pos: { x: 0, y: 1, z: 0 }, state: state('oak_planks') }
      ],
      blockEntities: [{ pos: { x: 2, y: 0, z: 2 }, id: 'minecraft:chest', nbt: { id: 'minecraft:chest', LootTable: 'minecraft:chests/simple_dungeon' } }],
      entities: [{ pos: { x: 1.5, y: 0, z: 1.5 }, nbt: { id: 'minecraft:pig' } }]
    })],
    source: { format: 'test', edition: 'java', dataVersion: 4189, gameVersion: '1.21.4' }
  });
}

/** Sort blocks so two structures can be compared without depending on iteration order. */
const blockList = (structure) => structure.main.blocks
  .map((block) => `${block.pos.x},${block.pos.y},${block.pos.z}=${block.state.toString()}${block.nbt ? '+nbt' : ''}`)
  .sort();

// Written here, at module scope, so every test below may read them. Regenerating them is idempotent, and the
