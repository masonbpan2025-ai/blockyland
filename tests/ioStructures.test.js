test('detection trusts CONTENT over the file name', () => {
  // The same bytes with a misleading name: a `.nbt` file holding a Sponge schematic must be read as Sponge,
  // because renaming a download is the normal case and the extension is the least reliable evidence there is.
  const spongeBytes = readFileSync(join(FIXTURES, 'house.schem'));
  const asNbt = detectFormat(spongeBytes, { filename: 'house.nbt' });
  assert.equal(asNbt.confidence, 'extension', 'compressed bytes cannot be sniffed without inflating them first');

  const javaBytes = readFileSync(join(FIXTURES, 'house.nbt'));
  const misnamed = detectFormat(javaBytes, { filename: 'house.schem' });
  assert.equal(misnamed.confidence, 'extension');
});

