test('the committed fixtures exist, parse, and re-serialize byte-for-byte', async () => {
  // A fixture that only ever lives in memory cannot catch a codec that agrees with itself but not with bytes
  // on disk. Re-serializing a parsed fixture and comparing bytes proves the writer is deterministic and that
  // the reader handled everything the writer produced.
  if (!existsSync(FIXTURES)) mkdirSync(FIXTURES, { recursive: true });
  const original = sampleStructure();

  const schemBytes = await writeSpongeSchematic(original);
  const nbtBytes = await writeJavaStructure(original);
  writeFileSync(join(FIXTURES, 'house.schem'), schemBytes);
  writeFileSync(join(FIXTURES, 'house.nbt'), nbtBytes);
  writeFileSync(join(FIXTURES, 'README.md'),
    '# IO fixtures\n\n'
    + 'Generated by `tests/ioStructures.test.js` from a description in that file, by our own writers, so nothing\n'
    + 'here is Mojang content and everything is redistributable. Regenerate with\n'
    + '`node --test tests/ioStructures.test.js`.\n\n'
    + '* `house.schem` - Sponge schematic v3 (gzipped NBT), 3x2x3: stone, oak stairs with properties, a chest\n'
    + '  with a loot table as a block entity, one block of air, and a pig entity.\n'
    + '* `house.nbt` - the same structure as a vanilla Java structure template.\n'
    + '* `worldedit_house.schem` - the same build, re-written by WorldEdit CLI 7.4.7 (full block-state forms).\n');

  for (const [file, reader, writer] of [
    ['house.schem', readSpongeSchematic, writeSpongeSchematic],
    ['house.nbt', readJavaStructure, writeJavaStructure]
  ]) {
    const onDisk = readFileSync(join(FIXTURES, file));
    const parsed = await reader(onDisk);
    assert.deepEqual(blockList(parsed.structure), blockList(original), `${file} must contain the sample structure`);
    const again = await writer(parsed.structure);
    assert.deepEqual([...again], [...onDisk], `${file} must re-serialize to the same bytes`);
  }
});
