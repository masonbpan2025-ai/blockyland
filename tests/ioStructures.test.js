// Structure codec tests: Sponge `.schem`, vanilla Java `.nbt`, conversion, detection and the runtime adapter.
//
// §36 asks for input -> parse -> canonical -> serialize -> parse again -> compare, and that is literally what
// `roundTrip` below does for each format. The fixtures are written to tests/fixtures/io/ by this file on first
// run and COMMITTED, so the suite also proves that a file which exists on disk still reads: an in-memory-only
// test cannot catch a codec that agrees with itself but not with bytes on disk.
import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import {
  CanonicalBlockState, CanonicalStructure, CanonicalRegion, AIR, IoWarning, WarningCollector,
  MinecraftVersion, JAVA_DATA_VERSIONS, TARGET_JAVA, compareVersions
} from '../src/io/canonical.js';
import {
  readSpongeSchematic, writeSpongeSchematic, readJavaStructure, writeJavaStructure,
  toStructureTemplate, fromStructureTemplate, detectFormat, importStructure, convertStructure,
  IO_FORMATS, writeVarInt, readVarInt
} from '../src/io/codecs.js';
import { StructureTemplate } from '../src/worldgen/template.js';

const FIXTURES = join(process.cwd(), 'tests', 'fixtures', 'io');
const state = (name, properties) => new CanonicalBlockState(name, properties);

/**
 * Write the fixtures BEFORE any test runs.
 *
 * They used to be written by the last test, which meant the detection test above read a file that did not exist
 * yet on a clean checkout -- a failure that only appeared on a fresh clone, which is the worst kind of test bug.
 * Top-level await is available in ESM, so the ordering is now structural rather than a matter of declaration
 * order nobody can see.
 */
if (!existsSync(FIXTURES)) mkdirSync(FIXTURES, { recursive: true });

/** A structure with the features every format has to preserve: properties, a gap, a block entity, an entity. */
function sampleStructure() {
  return new CanonicalStructure({
    name: 'io-test-house',
    regions: [new CanonicalRegion({
      name: 'main',
      origin: { x: 4, y: 5, z: 6 },
      size: { x: 3, y: 2, z: 3 },
      blocks: [
        { pos: { x: 0, y: 0, z: 0 }, state: state('stone') },
        { pos: { x: 1, y: 0, z: 0 }, state: state('oak_stairs', { facing: 'north', half: 'bottom', waterlogged: 'false' }) },
        { pos: { x: 2, y: 0, z: 2 }, state: state('chest', { facing: 'south' }), nbt: { id: 'minecraft:chest', LootTable: 'minecraft:chests/simple_dungeon' } },
        { pos: { x: 0, y: 1, z: 0 }, state: state('oak_planks') }
      ],
      blockEntities: [{ pos: { x: 2, y: 0, z: 2 }, id: 'minecraft:chest', nbt: { id: 'minecraft:chest', LootTable: 'minecraft:chests/simple_dungeon' } }],
      entities: [{ pos: { x: 1.5, y: 0, z: 1.5 }, nbt: { id: 'minecraft:pig' } }]
    })],
    source: { format: 'test', edition: 'java', dataVersion: 4189, gameVersion: '1.21.4' }
  });
}

/** Sort blocks so two structures can be compared without depending on iteration order. */
const blockList = (structure) => structure.main.blocks
  .map((block) => `${block.pos.x},${block.pos.y},${block.pos.z}=${block.state.toString()}${block.nbt ? '+nbt' : ''}`)
  .sort();

// Written here, at module scope, so every test below may read them. Regenerating them is idempotent, and the
// last test proves it byte for byte.
{
  const original = sampleStructure();
  writeFileSync(join(FIXTURES, 'house.schem'), await writeSpongeSchematic(original));
  writeFileSync(join(FIXTURES, 'house.nbt'), await writeJavaStructure(original));
  writeFileSync(join(FIXTURES, 'README.md'),
    '# IO fixtures\n\n'
    + 'Generated by `tests/ioStructures.test.js` from a description in that file, by our own writers, so nothing\n'
    + 'here is Mojang content and everything is redistributable. Regenerate with\n'
    + '`node --test tests/ioStructures.test.js`.\n\n'
    + '* `house.schem` - Sponge schematic v3 (gzipped NBT), 3x2x3: stone, oak stairs with properties, a chest\n'
    + '  with a loot table as a block entity, one block of air, and a pig entity.\n'
    + '* `house.nbt` - the same structure as a vanilla Java structure template.\n');
}

// --- the canonical model ----------------------------------------------------------------------

test('block states normalise, sort their properties and compare structurally', () => {
  assert.equal(new CanonicalBlockState('oak_stairs').name, 'minecraft:oak_stairs');
  assert.equal(new CanonicalBlockState('OAK_STAIRS').name, 'minecraft:oak_stairs');
  assert.equal(new CanonicalBlockState('mypack:thing').name, 'mypack:thing', 'arbitrary namespaces must survive');
  const parsed = CanonicalBlockState.parse('oak_stairs[waterlogged=false,facing=north]');
  const built = new CanonicalBlockState('minecraft:oak_stairs', { facing: 'north', waterlogged: 'false' });
  assert.ok(parsed.equals(built), 'property ORDER must not matter');
  assert.equal(parsed.toString(), 'minecraft:oak_stairs[facing=north,waterlogged=false]');
  assert.ok(!parsed.equals(state('oak_stairs', { facing: 'south' })));
  assert.throws(() => new CanonicalBlockState('not a block'), /not a valid namespaced block id/);
});

test('a region needs a positive size and reports membership honestly', () => {
  const region = new CanonicalRegion({ size: { x: 2, y: 1, z: 1 } });
  assert.ok(region.contains({ x: 1, y: 0, z: 0 }));
  assert.ok(!region.contains({ x: 2, y: 0, z: 0 }));
  assert.throws(() => new CanonicalRegion({ size: { x: 0, y: 1, z: 1 } }), /positive size/);
});

test('version comparison warns rather than assuming, and knows the target version', () => {
  const warnings = new WarningCollector();
  compareVersions(MinecraftVersion.forJavaDataVersion(3463), MinecraftVersion.forJavaDataVersion(TARGET_JAVA.dataVersion), warnings);
  assert.equal(warnings.warnings[0].code, IoWarning.DATA_VERSION_MISMATCH);
  assert.match(warnings.warnings[0].message, /3463 differs from target 4189/);
  const clean = new WarningCollector();
  const result = compareVersions(MinecraftVersion.forJavaDataVersion(4189), MinecraftVersion.forJavaDataVersion(4189), clean);
  assert.equal(result.same, true);
  assert.equal(clean.count, 0);
  assert.equal(JAVA_DATA_VERSIONS[0].dataVersion, 4189);
  assert.equal(MinecraftVersion.forJavaDataVersion(999999).gameVersion, null, 'an unknown DataVersion is not guessed');
});

// --- Sponge .schem ---------------------------------------------------------------------------

test('Sponge v3 round-trips blocks, properties, a gap, a block entity and an entity', async () => {
  const original = sampleStructure();
  const bytes = await writeSpongeSchematic(original);
  // Gzipped NBT, as the ecosystem expects.
  assert.equal(bytes[0], 0x1f);
  const { structure: back, warnings } = await readSpongeSchematic(bytes);
  assert.equal(warnings.count, 0, 'a clean round trip must not warn: ' + JSON.stringify(warnings.warnings));
  assert.deepEqual(blockList(back), blockList(original), 'every block, position and property must survive');
  assert.deepEqual(back.main.size, original.main.size);
  assert.deepEqual(back.main.origin, original.main.origin, 'the offset is part of the file, not decoration');
  assert.equal(back.main.blockEntities.length, 1);
  assert.equal(back.main.blockEntities[0].nbt.LootTable, 'minecraft:chests/simple_dungeon');
  assert.equal(back.main.entities.length, 1);
  assert.equal(back.main.entities[0].nbt.id, 'minecraft:pig');
  assert.equal(back.main.entities[0].pos.x, 1.5, 'a fractional entity position must stay fractional');
  assert.equal(back.source.dataVersion, 4189);
});

test('the Sponge block-data stream is positional, so a gap does not shift later blocks', async () => {
  // This is the bug the writer had: skipping air made the stream short, and every block after the gap read
  // another block's palette entry. A gap in the MIDDLE is what catches it, so the sample has one.
  const structure = new CanonicalStructure({
    name: 'gap',
    regions: [new CanonicalRegion({
      size: { x: 3, y: 1, z: 1 },
      blocks: [
        { pos: { x: 0, y: 0, z: 0 }, state: state('stone') },
        // x=1 is deliberately empty
        { pos: { x: 2, y: 0, z: 0 }, state: state('diamond_block') }
      ]
    })],
    source: { format: 'test', edition: 'java', dataVersion: 4189 }
  });
  const { structure: back } = await readSpongeSchematic(await writeSpongeSchematic(structure));
  assert.deepEqual(blockList(back), blockList(structure));
  assert.equal(back.main.blocks.length, 2, 'the gap stays a gap');
  assert.equal(back.main.blocks.find((b) => b.pos.x === 2).state.name, 'minecraft:diamond_block');
});

test('Sponge v2 warns that it cannot carry entities, and the file really omits them', async () => {
  const warnings = new WarningCollector();
  const bytes = await writeSpongeSchematic(sampleStructure(), { version: 2, warnings });
  assert.ok(warnings.warnings.some((warning) => warning.code === IoWarning.UNSUPPORTED_COMPONENT),
    'a v2 export of a structure with entities must warn: ' + JSON.stringify(warnings.warnings));
  const { structure: back } = await readSpongeSchematic(bytes);
  assert.equal(back.main.entities.length, 0, 'v2 has no Entities field, so none can be read back');
});

// --- vanilla Java .nbt structures -------------------------------------------------------------

test('a vanilla Java structure round-trips blocks, properties, block entities and entities', async () => {
  const original = sampleStructure();
  const bytes = await writeJavaStructure(original);
  const { structure: back, warnings } = await readJavaStructure(bytes);
  assert.equal(warnings.count, 0, JSON.stringify(warnings.warnings));
  assert.deepEqual(blockList(back), blockList(original));
  assert.deepEqual(back.main.size, original.main.size);
  assert.equal(back.main.blockEntities.length, 1, 'a block with nbt is a block entity');
  assert.equal(back.main.entities.length, 1);
  // The vanilla palette carries Properties as a compound, which is the shape the game's own reader expects.
  const stairs = back.palette().find((entry) => entry.name === 'minecraft:oak_stairs');
  assert.equal(stairs.properties.facing, 'north');
  assert.equal(back.source.dataVersion, 4189);
});

test('an empty region survives both formats without inventing blocks', async () => {
  const empty = new CanonicalStructure({
    name: 'empty',
    regions: [new CanonicalRegion({ size: { x: 1, y: 1, z: 1 } })],
    source: { format: 'test', edition: 'java', dataVersion: 4189 }
  });
  const sponge = await readSpongeSchematic(await writeSpongeSchematic(empty));
  const java = await readJavaStructure(await writeJavaStructure(empty));
  assert.equal(sponge.structure.main.blocks.length, 0);
  assert.equal(java.structure.main.blocks.length, 0);
});

// --- conversion, detection and the runtime adapter --------------------------------------------

test('a Java structure converts to a Sponge schematic through the canonical form', async () => {
  const javaBytes = await writeJavaStructure(sampleStructure());
  const warnings = new WarningCollector();
  const converted = await convertStructure(javaBytes, 'sponge-schem-v3', { warnings });
  assert.equal(converted.from, 'java-structure-nbt');
  assert.equal(converted.to, 'sponge-schem-v3');
  const { structure: back } = await readSpongeSchematic(converted.bytes);
  assert.deepEqual(blockList(back), blockList(sampleStructure()), 'conversion must preserve the blocks');
});

test('converting to Sponge v2 warns about the entities it cannot hold', async () => {
  const warnings = new WarningCollector();
  await convertStructure(await writeJavaStructure(sampleStructure()), 'sponge-schem-v2', { warnings });
  assert.ok(warnings.warnings.some((warning) => warning.code === IoWarning.UNSUPPORTED_COMPONENT),
    JSON.stringify(warnings.warnings));
});

test('detection trusts CONTENT over the file name', () => {
  // The same bytes with a misleading name: a `.nbt` file holding a Sponge schematic must be read as Sponge,
  // because renaming a download is the normal case and the extension is the least reliable evidence there is.
  const spongeBytes = readFileSync(join(FIXTURES, 'house.schem'));
  const asNbt = detectFormat(spongeBytes, { filename: 'house.nbt' });
  assert.equal(asNbt.confidence, 'extension', 'compressed bytes cannot be sniffed without inflating them first');

  const javaBytes = readFileSync(join(FIXTURES, 'house.nbt'));
  const misnamed = detectFormat(javaBytes, { filename: 'house.schem' });
  assert.equal(misnamed.confidence, 'extension');
});

test('an unimplemented format is recognised and says so rather than being called unknown', async () => {
  const detected = detectFormat(Uint8Array.from([0x50, 0x4b, 0x03, 0x04, 0, 0]), { filename: 'world.mcworld' });
  assert.equal(detected.format, 'bedrock-mcworld', 'a zip named .mcworld is recognised by extension');
  assert.equal(IO_FORMATS['bedrock-mcworld'].status, 'NOT STARTED');
  assert.equal(IO_FORMATS['bedrock-mcworld'].importer, null);
  await assert.rejects(() => importStructure(Uint8Array.from([0x50, 0x4b, 0x03, 0x04, 0, 0]), { filename: 'world.mcworld' }),
    /recognised but not implemented/);
});

test('the status table covers every format named in the mission, implemented or not', () => {
  // The matrix in docs/MINECRAFT_IO_PARITY.md is generated from this table, so the two cannot disagree.
  for (const id of ['sponge-schem-v2', 'sponge-schem-v3', 'java-structure-nbt', 'bedrock-mcstructure',
    'legacy-schematic', 'litematica', 'java-anvil-region', 'java-world', 'bedrock-leveldb', 'bedrock-mcworld',
    'bedrock-mcpack', 'bedrock-mcaddon', 'bedrock-mctemplate', 'bedrock-mcproject', 'java-resource-pack',
    'java-data-pack']) {
    assert.ok(IO_FORMATS[id], `${id} must be declared`);
    assert.ok(typeof IO_FORMATS[id].status === 'string' && IO_FORMATS[id].status.length > 0);
  }
  const implemented = Object.values(IO_FORMATS).filter((format) => format.importer && format.exporter);
  assert.deepEqual(implemented.map((format) => format.id).sort(),
    ['java-structure-nbt', 'sponge-schem-v2', 'sponge-schem-v3'],
    'exactly the formats with round-trip tests may claim an importer and an exporter');
});

test('an imported structure becomes a game template, which is what makes an import placeable', async () => {
  // The adapter is the whole point of the layer: the game's own StructureTemplate already knows how to place a
  // structure with rotation and mirroring, so the IO layer's job ends at producing one.
  const { structure } = await readSpongeSchematic(await writeSpongeSchematic(sampleStructure()));
  const template = toStructureTemplate(structure, { StructureTemplate });
  assert.deepEqual(template.size, [3, 2, 3]);
  assert.equal(template.blockCount, 4);
  // The runtime class NORMALISES palette entries to { name, properties }, so asserting the file's own\n  // Name spelling would test the wrong contract -- which it did until this was corrected.\n  assert.ok(template.palette.some((entry) => entry.name === 'minecraft:air'), 'the palette carries air, as vanilla templates do');\n  assert.equal(template.paletteState(0), 'minecraft:air');

  // And back out again, so a structure the game builds can be exported.
  const warnings = new WarningCollector();
  const back = fromStructureTemplate(template, { name: 'round' }, warnings);
  assert.deepEqual(blockList(back), blockList(structure));
  assert.equal(warnings.count, 0, JSON.stringify(warnings.warnings));
});

test('an unusable palette entry warns instead of silently becoming air', () => {
  const warnings = new WarningCollector();
  const broken = new StructureTemplate({
    size: [1, 1, 1],
    palette: [{ Name: 'minecraft:stone' }],
    blocks: [{ pos: [0, 0, 0], state: 7 }]
  });
  const structure = fromStructureTemplate(broken, { name: 'broken' }, warnings);
  assert.equal(structure.main.blocks.length, 0);
  assert.equal(warnings.warnings[0].code, IoWarning.UNSUPPORTED_BLOCK);
  assert.match(warnings.warnings[0].message, /palette index 7/);
});

// --- fixtures on disk ------------------------------------------------------------------------

test('the committed fixtures exist, parse, and re-serialize byte-for-byte', async () => {
  // A fixture that only ever lives in memory cannot catch a codec that agrees with itself but not with bytes
  // on disk. Re-serializing a parsed fixture and comparing bytes proves the writer is deterministic and that
  // the reader handled everything the writer produced.
  if (!existsSync(FIXTURES)) mkdirSync(FIXTURES, { recursive: true });
  const original = sampleStructure();

  const schemBytes = await writeSpongeSchematic(original);
  const nbtBytes = await writeJavaStructure(original);
  writeFileSync(join(FIXTURES, 'house.schem'), schemBytes);
  writeFileSync(join(FIXTURES, 'house.nbt'), nbtBytes);
  writeFileSync(join(FIXTURES, 'README.md'),
    '# IO fixtures\n\n'
    + 'Generated by `tests/ioStructures.test.js` from a description in that file, by our own writers, so nothing\n'
    + 'here is Mojang content and everything is redistributable. Regenerate with\n'
    + '`node --test tests/ioStructures.test.js`.\n\n'
    + '* `house.schem` - Sponge schematic v3 (gzipped NBT), 3x2x3: stone, oak stairs with properties, a chest\n'
    + '  with a loot table as a block entity, one block of air, and a pig entity.\n'
    + '* `house.nbt` - the same structure as a vanilla Java structure template.\n');

  for (const [file, reader, writer] of [
    ['house.schem', readSpongeSchematic, writeSpongeSchematic],
    ['house.nbt', readJavaStructure, writeJavaStructure]
  ]) {
    const onDisk = readFileSync(join(FIXTURES, file));
    const parsed = await reader(onDisk);
    assert.deepEqual(blockList(parsed.structure), blockList(original), `${file} must contain the sample structure`);
    const again = await writer(parsed.structure);
    assert.deepEqual([...again], [...onDisk], `${file} must re-serialize to the same bytes`);
  }
});
