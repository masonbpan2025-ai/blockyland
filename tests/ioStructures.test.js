test('an imported structure becomes a game template, which is what makes an import placeable', async () => {
  // The adapter is the whole point of the layer: the game's own StructureTemplate already knows how to place a
  // structure with rotation and mirroring, so the IO layer's job ends at producing one.
  const { structure } = await readSpongeSchematic(await writeSpongeSchematic(sampleStructure()));
  const template = toStructureTemplate(structure, { StructureTemplate });
  assert.deepEqual(template.size, [3, 2, 3]);
  assert.equal(template.blockCount, 4);
  // The runtime class NORMALISES palette entries to { name, properties }, so asserting the file's own\n  // Name spelling would test the wrong contract -- which it did until this was corrected.\n  assert.ok(template.palette.some((entry) => entry.name === 'minecraft:air'), 'the palette carries air, as vanilla templates do');\n  assert.equal(template.paletteState(0), 'minecraft:air');

  // And back out again, so a structure the game builds can be exported.
  const warnings = new WarningCollector();
  const back = fromStructureTemplate(template, { name: 'round' }, warnings);
  assert.deepEqual(blockList(back), blockList(structure));
  assert.equal(warnings.count, 0, JSON.stringify(warnings.warnings));
});

