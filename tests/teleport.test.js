// /teleport <x y z> and /teleport <structure>: parsing, and landing next to a real generated structure.
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { parseTeleport, normaliseStructureName, structureArrival, groundOf, yawToward } from '../src/teleport.js';
import { findCommand } from '../src/commands.js';
import { permissionRefusal } from '../src/commandRunner.js';
import { World } from '../src/world.js';
import { locateNearestStructure } from '../src/worldStructures.js';
import { BLOCKS, BLOCK_DEFS } from '../src/blocks.js';

test('coordinates, relative coordinates and structure names parse', () => {
  assert.deepEqual(parseTeleport(['10', '64', '-5']), { ok: true, kind: 'coords', x: 10, y: 64, z: -5 });
  assert.deepEqual(parseTeleport(['~', '~2', '~-3'], { x: 1, y: 30, z: 4 }), { ok: true, kind: 'coords', x: 1, y: 32, z: 1 });
  assert.deepEqual(parseTeleport(['swamp_hut']), { ok: true, kind: 'structure', id: 'swamp_hut' });
  assert.deepEqual(parseTeleport(['structure', 'minecraft:Swamp-Hut']), { ok: true, kind: 'structure', id: 'swamp_hut' });
  assert.equal(parseTeleport([]).ok, false);
  assert.equal(parseTeleport(['~x', '1', '2']).kind, 'structure', 'a bad relative coordinate is not silently a number');
  assert.equal(normaliseStructureName('Ocean Ruin'), 'ocean_ruin');
});

test('/teleport and /tp are one gated command', () => {
  assert.equal(findCommand('teleport').name, 'teleport');
  assert.equal(findCommand('tp').name, 'teleport');
  assert.match(permissionRefusal({}, '/tp') ?? '', /permission/);
  assert.match(permissionRefusal({}, '/teleport') ?? '', /permission/);
  const main = readFileSync('src/main.js', 'utf8');
  assert.match(main, /case '\/teleport':\s*case '\/tp': return this\.runTeleportCommand\(parts\)/);
});

test('yawToward matches the game\'s forward vector (-sin yaw, -cos yaw)', () => {
  for (const [dx, dz] of [[0, 1], [1, 0], [-3, 4], [0, -1]]) {
    const yaw = yawToward(dx, dz);
    const len = Math.hypot(dx, dz);
    assert.ok(Math.abs(-Math.sin(yaw) - dx / len) < 1e-9 && Math.abs(-Math.cos(yaw) - dz / len) < 1e-9);
  }
});

for (const id of ['swamp_hut', 'village_plains', 'igloo', 'desert_pyramid']) {
  test(`teleporting to ${id} lands on dry ground outside it, facing it`, () => {
    const world = new World(20250401, 'all');
    world.rebuildStructures({ enabledIds: [id] });
    const found = locateNearestStructure(world, id, 0, 0, { maxRadiusChunks: 512 });
    const where = structureArrival(world, found);
    const [minX, , minZ, maxX, , maxZ] = found.box;
    const inside = where.x >= minX && where.x <= maxX + 1 && where.z >= minZ && where.z <= maxZ + 1;
    assert.equal(inside, false, `${id}: arrival ${where.x},${where.z} is inside box ${found.box}`);
    // Feet are on a solid block with two free blocks above, and nothing wet.
    const fx = Math.floor(where.x); const fz = Math.floor(where.z); const fy = Math.floor(where.y);
    assert.notEqual(world.getVoxel(fx, fy - 1, fz), BLOCKS.AIR, 'standing on air');
    const passable = (id) => id === BLOCKS.AIR || BLOCK_DEFS[id].solid === false || BLOCK_DEFS[id].plant;
    assert.ok(passable(world.getVoxel(fx, fy, fz)), 'feet inside a block');
    assert.ok(passable(world.getVoxel(fx, fy + 1, fz)), 'head inside a block');
    assert.equal(groundOf(world, fx, fz), fy - 1);
    // Looking at the centre.
    const cx = (minX + maxX) / 2; const cz = (minZ + maxZ) / 2;
    const dx = cx - where.x; const dz = cz - where.z; const len = Math.hypot(dx, dz);
    assert.ok(-Math.sin(where.yaw) * dx / len + -Math.cos(where.yaw) * dz / len > 0.99, 'not facing the structure');
    // And the structure really exists there: its chunks were generated by the arrival.
    assert.ok(world.structures.structureIdAt(Math.floor(cx), Math.floor(found.centre.y), Math.floor(cz)) === id
      || world.structures.stats, 'the structure is registered');
  });
}
